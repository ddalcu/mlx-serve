#!/usr/bin/env python3
"""Generate src/sdk/tokenizer/nfc_table.zig from Python's unicodedata.

Usage: python3 -I scripts/gen_nfc_table.py > src/sdk/tokenizer/nfc_table.zig && zig fmt src/sdk/tokenizer/nfc_table.zig

The tables follow the Unicode version of the Python that runs this script;
the header records it. Hangul syllables are left out: nfc.zig decomposes and
composes them algorithmically (Unicode 3.12).
"""

import sys
import unicodedata as ud

PER_LINE = 6


def is_hangul(cp):
    return 0xAC00 <= cp < 0xAC00 + 11172


def canonical(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def rows(name, entries, doc):
    out = [f"/// {doc}", f"pub const {name} = [_][3]u21{{"]
    for i in range(0, len(entries), PER_LINE):
        chunk = entries[i : i + PER_LINE]
        out.append("    " + " ".join(".{ " + ", ".join(f"0x{v:04X}" for v in e) + " }," for e in chunk))
    out.append("};")
    return out


def main():
    decomp, comp, ccc = [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        c = ud.combining(chr(cp))
        if c:
            if ccc and ccc[-1][1] == cp - 1 and ccc[-1][2] == c:
                ccc[-1][1] = cp
            else:
                ccc.append([cp, cp, c])
        if is_hangul(cp):
            continue
        d = canonical(cp)
        if d is None:
            continue
        assert len(d) in (1, 2), hex(cp)
        decomp.append((cp, d[0], d[1] if len(d) == 2 else 0))
        # A primary composite: a pair that NFC turns back into this code point.
        if len(d) == 2 and ud.normalize("NFC", chr(d[0]) + chr(d[1])) == chr(cp):
            comp.append((d[0], d[1], cp))
    comp.sort()

    lines = [
        "//! Unicode canonical tables for NFC, generated by scripts/gen_nfc_table.py",
        f"//! from Python {sys.version.split()[0]} unicodedata (Unicode {ud.unidata_version}).",
        "//! Do not edit by hand: rerun the script.",
        "",
    ]
    lines += rows("decomp", decomp, "Canonical decomposition `{ code point, first, second or 0 }`, sorted by code point.")
    lines.append("")
    lines += rows("comp", comp, "Primary composites `{ first, second, composed }`, sorted by (first, second).")
    lines.append("")
    lines += rows("ccc", [tuple(r) for r in ccc], "Nonzero canonical combining class ranges `{ first, last, class }`, sorted.")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
