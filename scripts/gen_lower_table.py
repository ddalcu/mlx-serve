#!/usr/bin/env python3
"""Generate src/plugins/heartmula/lower_table.zig: Python's `str.lower` as tables.

Usage: python3 -I scripts/gen_lower_table.py > src/plugins/heartmula/lower_table.zig && zig fmt src/plugins/heartmula/lower_table.zig

`str.lower` is a one-to-one map for almost every code point, a few full mappings to several code points (U+0130),
and the Final_Sigma rule: a capital sigma lowercases to final sigma when a cased letter precedes it and none follows,
skipping case-ignorable code points on both sides. `unicodedata` exposes neither set, so both are read off CPython's
own sigma handling:
  ("x" + "Σ").lower() ends in "ς"        <=> x is cased and not case-ignorable
  ("A" + x + "Σ").lower() ends in "ς"    <=> x is case-ignorable, or cased
Every table is checked against `str.lower` before it is written.
"""

import sys
import unicodedata as ud

PER_LINE = 6


def code_points():
    for cp in range(0x110000):
        if not 0xD800 <= cp < 0xE000:
            yield cp


def runs(pairs):
    """`(cp, lower)` pairs, sorted, as `{first, last, delta, stride}` runs (stride 1 or 2)."""
    out = []
    for cp, lo in pairs:
        d = lo - cp
        if out:
            first, last, delta, stride = out[-1]
            if delta == d and (cp - last) in (1, 2) and (first == last or cp - last == stride):
                out[-1] = [first, cp, delta, cp - last if first == last else stride]
                continue
        out.append([cp, cp, d, 1])
    return out


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def table(name, typ, rows, doc):
    lines = [f"/// {doc}", f"pub const {name} = [_]{typ}{{"]
    for i in range(0, len(rows), PER_LINE):
        chunk = rows[i : i + PER_LINE]
        lines.append("    " + " ".join(".{ " + ", ".join(fmt(v) for v in r) + " }," for r in chunk))
    lines.append("};")
    return lines


def fmt(v):
    return f"0x{v:04X}" if v >= 0 else str(v)


def main():
    simple, multi, cased, ignorable = [], [], [], []
    for cp in code_points():
        c = chr(cp)
        lo = c.lower() if cp != 0x03A3 else "σ"
        if len(lo) == 1 and lo != c:
            simple.append((cp, ord(lo)))
        elif len(lo) > 1:
            multi.append((cp, [ord(x) for x in lo]))
        before = (c + "Σ").lower().endswith("ς")
        either = ("A" + c + "Σ").lower().endswith("ς")
        if before:
            cased.append(cp)
        elif either:
            ignorable.append(cp)

    simple_runs = runs(simple)
    want = dict(simple)
    for first, last, delta, stride in simple_runs:
        for cp in range(first, last + 1, stride):
            assert want.pop(cp) == cp + delta, hex(cp)
    assert not want
    # disjoint and sorted: `simpleLower` binary-searches on `last`
    assert all(a[1] < b[0] for a, b in zip(simple_runs, simple_runs[1:]))
    assert all(len(m) <= 3 for _, m in multi)

    lines = [
        "//! Python's `str.lower` as tables, generated by scripts/gen_lower_table.py",
        f"//! from Python {sys.version.split()[0]} (Unicode {ud.unidata_version}). Do not edit by hand: rerun the script.",
        "",
    ]
    lines += table("simple", "Run", simple_runs,
                   "One-to-one lowercase `{ first, last, delta, stride }`: every stride-th code point in [first, last] maps to cp + delta.")
    lines.append("")
    lines += table("multi", "[4]u21", [(cp, *m, *([0] * (3 - len(m)))) for cp, m in multi],
                   "Full mappings to several code points `{ cp, lower..., 0 }`.")
    lines.append("")
    lines += table("cased", "[2]u21", ranges(cased), "Cased and not case-ignorable, inclusive ranges (Final_Sigma's context).")
    lines.append("")
    lines += table("case_ignorable", "[2]u21", ranges(ignorable), "Case-ignorable, inclusive ranges (skipped by Final_Sigma).")
    lines.append("")
    lines.append("pub const Run = struct { u21, u21, i32, u21 };")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
