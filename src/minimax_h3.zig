            }
            testing.expectApproxEqRel(jsonF64(ps[k]), sum, 1e-9) catch |e| {
                std.debug.print("case {s}: position axis {d} checksum mismatch\n", .{ name, k });
                return e;
            };
            testing.expectApproxEqRel(jsonF64(pw[k]), weighted, 1e-9) catch |e| {
                std.debug.print("case {s}: position axis {d} ORDER mismatch\n", .{ name, k });
                return e;
            };
        }

        // Per-segment first row: localizes a failure to one segment rather than
        // reporting a single wrong number for the whole sequence.
        const sfp = o.get("seg_first_pos").?.array.items;
        try testing.expectEqual(layout.segments.len, sfp.len);
