        // would be trivially satisfied by a no-op rope.
        const head = try sliceLast4(rotated, 0, @intCast(cfg.rotDim()), s);
        defer _ = mlx.mlx_array_free(head);
        const head_ones = try sliceLast4(ones, 0, @intCast(cfg.rotDim()), s);
        defer _ = mlx.mlx_array_free(head_ones);
        const moved = try cosineSim(head, head_ones, s);
        try testing.expect(std.math.isFinite(moved));
        try testing.expect(moved < 0.999);
    }
