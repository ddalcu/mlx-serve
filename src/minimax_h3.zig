//! MiniMax H3 (Hailuo 3.0) audio-video DiT — packed-layout and schedule math.
//!
//! H3 denoises video (24ch, patch 1x2x2) and stereo audio (32ch, 40 Hz) latents
//! JOINTLY in one full-attention stream conditioned on Qwen3-VL-32B layer-50
//! hidden states. The packed sequence is
//!     [text | cond rows | audio | video]   (t2va / fl2va)
//!     [text | reference blocks | audio | video]  (ref2va)
//! and every row carries a 3D (t, h, w) position feeding a partial split-half
//! RoPE (rot_dim 96 of head_dim 128, 16 inverse frequencies per axis).
//!
//! This file is the WEIGHTLESS layer: the frame ladder, the canvas rule, the
//! dual sigma schedule, the position grids and the packed layout. It is pinned
//! by a hermetic test against `fixtures/minimax_h3_layout.json`, which is
//! generated by `tests/dump_minimax_h3_layout.py` calling ComfyUI's own
//! `comfy/ldm/minimax/model.py` — the golden values are the reference's output,
//! never a transcription of its formulas.
//!
//! Three things here are easy to get subtly wrong and produce a model that runs
//! and generates the WRONG video rather than erroring:
//!   1. Frame counts live on a 17k+5 ladder (5, 22, 39, 56, ... 124 ... 362).
//!      Not LTX's 8N+1. The VAE folds 17 source frames into 5 latent frames.
//!   2. Position coordinates are AREA-NORMALIZED, not raw indices: each axis is
//!      a half-open linspace over (1-ratio)/2 .. (1+ratio)/2 scaled by 32, with
//!      ratio = dim / sqrt(h*w). Aspect ratio therefore moves every position.
//!   3. Temporal spans cycle FRAME_PER_TOKEN (1,4,4,4,4) * 5/3, so latent frame
//!      k covers 1 or 4 source frames depending on k % 5 — the grid is NOT
//!      uniformly spaced.

