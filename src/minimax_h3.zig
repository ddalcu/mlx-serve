    try testing.expectApproxEqAbs(@as(f64, 0.5), p1.unique_t[0], 1e-12);
    try testing.expectApproxEqAbs(@as(f64, 0.8), p1.unique_t[1], 1e-12);
    // text (tag 1) and video (tag 0) share the video timestep row 0;
    // audio (tag 2) sits on row 1.
    try testing.expectEqual(@as(u32, 0 * 3 + 1), p1.runs[0].mod_row); // text
    try testing.expectEqual(@as(u32, 1 * 3 + 2), p1.runs[1].mod_row); // audio
    try testing.expectEqual(@as(u32, 0 * 3 + 0), p1.runs[2].mod_row); // video

    // fl2va: the keyframe rows pin near 1 via the visual aug, adding a third
    // distinct timestep — the row the AdaLN reshape must have space for.
    var l2 = try PackedLayout.init(a, 512, 17, 30, 54, 93, &.{.first}, 56);
    defer l2.deinit();
    var p2 = try buildTimestepPlan(a, &l2, 0.5, SIGMA_SHIFT_VIDEO, SIGMA_SHIFT_AUDIO, .{});
    defer p2.deinit();
    try testing.expectEqual(@as(usize, 3), p2.n_unique);
    try testing.expectApproxEqAbs(VISUAL_COND_TIMESTEP, p2.unique_t[2], 1e-12);
    // The cond segment carries the VIDEO modality tag but the condition
    // timestep — mixing those up modulates clean rows as if they were noisy.
    const cond_run = p2.runs[1];
    try testing.expectEqual(SegmentKind.cond, l2.segments[1].kind);
    try testing.expectEqual(@as(u32, 2 * 3 + 0), cond_run.mod_row);

    // Every run must address a row the AdaLN output actually has.
    for (p2.runs) |r| try testing.expect(r.mod_row < p2.n_unique * 3);

    // Runs tile the sequence exactly — a gap would leave rows unmodulated and
    // an overlap would modulate them twice.
    var cursor: u32 = 0;
    for (p2.runs) |r| {
        try testing.expectEqual(cursor, r.start);
        cursor = r.end;
    }
    try testing.expectEqual(l2.seq_len, cursor);
}

/// Cosine similarity between two arrays, with a FINITENESS check first.
/// `NaN > threshold` is false, so an all-NaN candidate scores a perfect 0 error
/// and sails through any comparison that diffs before it checks.
fn cosineSim(a_arr: mlx.mlx_array, b_arr: mlx.mlx_array, s: S) !f32 {
    const af = try astype(a_arr, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(af);
    const bf = try astype(b_arr, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(bf);
    const n: c_int = @intCast(mlx.mlx_array_size(af));
    const a1 = try reshape(af, &[_]c_int{n}, s);
    defer _ = mlx.mlx_array_free(a1);
    const b1 = try reshape(bf, &[_]c_int{n}, s);
    defer _ = mlx.mlx_array_free(b1);

    const dot = try sumAll(try mulOwned(a1, b1, s), s);
    const na = try sumAll(try mulOwned(a1, a1, s), s);
    const nb = try sumAll(try mulOwned(b1, b1, s), s);
    if (!std.math.isFinite(dot) or !std.math.isFinite(na) or !std.math.isFinite(nb)) return std.math.nan(f32);
    if (na <= 0 or nb <= 0) return std.math.nan(f32);
    return dot / (@sqrt(na) * @sqrt(nb));
}

fn mulOwned(a_arr: mlx.mlx_array, b_arr: mlx.mlx_array, s: S) !mlx.mlx_array {
    return mulA(a_arr, b_arr, s);
}

fn sumAll(x: mlx.mlx_array, s: S) !f32 {
    defer _ = mlx.mlx_array_free(x);
    var o = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o);
    try mlx.check(mlx.mlx_sum(&o, x, false, s));
    try mlx.check(mlx.mlx_array_eval(o));
    var v: f32 = 0;
    try mlx.check(mlx.mlx_array_item_float32(&v, o));
    return v;
}

