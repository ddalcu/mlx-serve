test "minimax h3: packed layout matches the reference segment table" {
    const a = testing.allocator;
    var parsed = try loadFixture(a);
    defer parsed.deinit();

    for (parsed.value.object.get("packed_layout").?.array.items) |item| {
        const o = item.object;
        const name = o.get("name").?.string;

        // The fixture's keyframe set is implied by its segment table: the
        // reference emits one "cond" segment per anchored keyframe, first then
        // last. Deriving it here keeps the test honest about what it feeds in.
        var anchors: [2]KeyframeAnchor = undefined;
        var n_anchors: usize = 0;
        for (o.get("segments").?.array.items) |seg| {
            if (std.mem.eql(u8, seg.array.items[2].string, "cond")) {
                anchors[n_anchors] = if (n_anchors == 0) .first else .last;
                n_anchors += 1;
            }
        }

        var layout = try PackedLayout.init(
            a,
            jsonU32(o.get("text_len").?),
            jsonU32(o.get("latent_t").?),
            jsonU32(o.get("latent_h").?),
            jsonU32(o.get("latent_w").?),
            jsonU32(o.get("audio_t").?),
            anchors[0..n_anchors],
            jsonU32(o.get("frame_count").?),
        );
        defer layout.deinit();

        testing.expectEqual(jsonU32(o.get("seq_len").?), layout.seq_len) catch |e| {
            std.debug.print("case {s}: seq_len mismatch\n", .{name});
            return e;
        };

        const want_segs = o.get("segments").?.array.items;
        try testing.expectEqual(want_segs.len, layout.segments.len);
        for (want_segs, 0..) |ws, i| {
            const arr = ws.array.items;
            try testing.expectEqual(jsonU32(arr[0]), layout.segments[i].start);
            try testing.expectEqual(jsonU32(arr[1]), layout.segments[i].end);
            try testing.expectEqual(
                SegmentKind.fromString(arr[2].string).?,
                layout.segments[i].kind,
            );
        }

        // position_ids: ends plus a per-axis checksum. Embedding the whole
        // [S,3] grid would be megabytes, and a checksum over 7.5K rows catches
        // any ordering or coordinate error that the ends alone would miss.
        const pf = o.get("pos_first").?.array.items;
        const pl = o.get("pos_last").?.array.items;
        const last = (layout.seq_len - 1) * 3;
        for (0..3) |k| {
            try testing.expectApproxEqAbs(jsonF64(pf[k]), layout.position_ids[k], 1e-9);
            try testing.expectApproxEqAbs(jsonF64(pl[k]), layout.position_ids[last + k], 1e-9);
        }
        const ps = o.get("pos_sum").?.array.items;
        const pw = o.get("pos_weighted").?.array.items;
        for (0..3) |k| {
            var sum: f64 = 0;
            // A plain column sum is permutation-INVARIANT — swapping the two
            // stereo channels' pinned w coordinates leaves it unchanged — so it
            // is paired with a row-index-weighted sum that is order-sensitive.
            var weighted: f64 = 0;
            var i: usize = 0;
            while (i < layout.seq_len) : (i += 1) {
                const v = layout.position_ids[i * 3 + k];
                sum += v;
                weighted += v * @as(f64, @floatFromInt(i + 1));
            }
            testing.expectApproxEqRel(jsonF64(ps[k]), sum, 1e-9) catch |e| {
                std.debug.print("case {s}: position axis {d} checksum mismatch\n", .{ name, k });
                return e;
            };
            testing.expectApproxEqRel(jsonF64(pw[k]), weighted, 1e-9) catch |e| {
                std.debug.print("case {s}: position axis {d} ORDER mismatch\n", .{ name, k });
                return e;
            };
        }

        // Per-segment first row: localizes a failure to one segment rather than
        // reporting a single wrong number for the whole sequence.
        const sfp = o.get("seg_first_pos").?.array.items;
        try testing.expectEqual(layout.segments.len, sfp.len);
        for (sfp, 0..) |row_v, si| {
            const want = row_v.array.items;
            const base = @as(usize, layout.segments[si].start) * 3;
            for (0..3) |k| {
                testing.expectApproxEqAbs(jsonF64(want[k]), layout.position_ids[base + k], 1e-9) catch |e| {
                    std.debug.print("case {s}: segment {d} ({s}) axis {d} first-row mismatch\n", .{
                        name, si, @tagName(layout.segments[si].kind), k,
                    });
                    return e;
                };
            }
        }

        var img_true: u32 = 0;
        for (layout.img_update) |v| img_true += @intFromBool(v);
        try testing.expectEqual(jsonU32(o.get("img_update_true").?), img_true);
        var aud_true: u32 = 0;
        for (layout.audio_update) |v| aud_true += @intFromBool(v);
        try testing.expectEqual(jsonU32(o.get("audio_update_true").?), aud_true);

        // The final layer slices the target streams by position, so "audio and
        // video are the last two segments" is a load-bearing promise, not an
        // incidental ordering.
        try testing.expectEqual(SegmentKind.video, layout.videoSegment().kind);
        try testing.expectEqual(SegmentKind.audio, layout.audioSegment().kind);
        try testing.expectEqual(layout.seq_len, layout.videoSegment().end);
    }
}

