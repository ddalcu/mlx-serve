// ── Attention ───────────────────────────────────────────────────────────────

/// Precomputed rotary tables for one packed layout. cos/sin are [S, rot/2].
pub const RopeTables = struct {
    cos: mlx.mlx_array,
    sin: mlx.mlx_array,

    pub fn deinit(self: *RopeTables) void {
        _ = mlx.mlx_array_free(self.cos);
        _ = mlx.mlx_array_free(self.sin);
    }
};

/// Build cos/sin from the layout's [S,3] positions and the checkpoint's
/// inv_freq [16]. Angles are concat(t*inv, h*inv, w*inv) = 48 values, and the
/// split-half pairing rotates dim i against dim i+48.
pub fn buildRope(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    inv_freq: mlx.mlx_array,
    dt: mlx.mlx_dtype,
    s: S,
) !RopeTables {
    const n = layout.seq_len;
    const nf = mlx.getShape(inv_freq)[0]; // 16
    const half: usize = @as(usize, @intCast(nf)) * 3; // 48

    // Positions ride to the GPU as f32. The reference builds the grid in f64
    // and casts here, so this cast is the reference's, not a shortcut.
    const pos_f32 = try allocator.alloc(f32, @as(usize, n) * 3);
    defer allocator.free(pos_f32);
    for (layout.position_ids, 0..) |v, i| pos_f32[i] = @floatCast(v);

    const shape = [_]c_int{ @intCast(n), 3, 1 };
    const pos = mlx.mlx_array_new_data(pos_f32.ptr, &shape, 3, mlx.mlx_dtype.float32);
    defer _ = mlx.mlx_array_free(pos);

    const inv_shape = [_]c_int{ 1, 1, @intCast(nf) };
    const inv3 = try reshape(inv_freq, &inv_shape, s);
    defer _ = mlx.mlx_array_free(inv3);
    const inv_f32 = try astype(inv3, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(inv_f32);

    // [S,3,1] * [1,1,16] -> [S,3,16] -> [S,48], axis order t,h,w
    const per_axis = try mulA(pos, inv_f32, s);
    defer _ = mlx.mlx_array_free(per_axis);
    const ang = try reshape(per_axis, &[_]c_int{ @intCast(n), @intCast(half) }, s);
    defer _ = mlx.mlx_array_free(ang);

    var c = mlx.mlx_array_new();
    errdefer _ = mlx.mlx_array_free(c);
    try mlx.check(mlx.mlx_cos(&c, ang, s));
    var sn = mlx.mlx_array_new();
    errdefer _ = mlx.mlx_array_free(sn);
    try mlx.check(mlx.mlx_sin(&sn, ang, s));

    // Broadcast slot for [1, S, 1, half] against q/k [1, S, H, head_dim].
    const bshape = [_]c_int{ 1, @intCast(n), 1, @intCast(half) };
    const cb = try reshape(c, &bshape, s);
    _ = mlx.mlx_array_free(c);
    errdefer _ = mlx.mlx_array_free(cb);
    const sb = try reshape(sn, &bshape, s);
    _ = mlx.mlx_array_free(sn);
    errdefer _ = mlx.mlx_array_free(sb);

    const cd = try astype(cb, dt, s);
    _ = mlx.mlx_array_free(cb);
    errdefer _ = mlx.mlx_array_free(cd);
    const sd = try astype(sb, dt, s);
    _ = mlx.mlx_array_free(sb);
    return .{ .cos = cd, .sin = sd };
}

/// Partial split-half rotary on [1, S, H, head_dim]: dims [0,48) pair with
/// [48,96); dims [96,128) pass through UNROTATED. Getting the pass-through
/// wrong (rotating the full head) is silent — the model still runs.
pub fn applyRopePub(x: mlx.mlx_array, rope: RopeTables, half: c_int, head_dim: c_int, s: S) !mlx.mlx_array {
    const x1 = try sliceLast4(x, 0, half, s);
    defer _ = mlx.mlx_array_free(x1);
    const x2 = try sliceLast4(x, half, half * 2, s);
    defer _ = mlx.mlx_array_free(x2);

    const a1 = try mulA(x1, rope.cos, s);
    defer _ = mlx.mlx_array_free(a1);
    const a2 = try mulA(x2, rope.sin, s);
    defer _ = mlx.mlx_array_free(a2);
    var o1 = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o1);
    try mlx.check(mlx.mlx_subtract(&o1, a1, a2, s));

    const b1 = try mulA(x1, rope.sin, s);
    defer _ = mlx.mlx_array_free(b1);
    const b2 = try mulA(x2, rope.cos, s);
    defer _ = mlx.mlx_array_free(b2);
    const o2 = try addA(b1, b2, s);
    defer _ = mlx.mlx_array_free(o2);

    if (half * 2 == head_dim) return concat(&[_]mlx.mlx_array{ o1, o2 }, 3, s);
    const tail = try sliceLast4(x, half * 2, head_dim, s);
    defer _ = mlx.mlx_array_free(tail);
    return concat(&[_]mlx.mlx_array{ o1, o2, tail }, 3, s);
}

/// x [S, hidden] -> [S, hidden]. Full bidirectional attention (no mask): this
/// is a diffusion transformer, every token sees every other.
fn attnForward(aw: *const AttnW, x: mlx.mlx_array, cfg: Config, rope: ?RopeTables, s: S) !mlx.mlx_array {
    const n: c_int = @intCast(mlx.getShape(x)[0]);
    const h: c_int = @intCast(cfg.num_attention_heads);
    const hd: c_int = @intCast(cfg.attention_head_dim);
    const half: c_int = @intCast(cfg.rotDim() / 2);

    const qkv = try aw.qkv.forward(x, null, s);
    defer _ = mlx.mlx_array_free(qkv);
    var parts: [3]mlx.mlx_array = undefined;
    try splitEqual(qkv, 3, 1, &parts, s);
    defer for (&parts) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    var qkvn: [3]mlx.mlx_array = undefined;
    var built: usize = 0;
    errdefer for (qkvn[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    for (0..3) |i| {
        // [S, inner] -> [1, S, H, hd]
        const v4 = try reshape(parts[i], &[_]c_int{ 1, n, h, hd }, s);
        if (i == 2) {
            qkvn[i] = v4;
            built += 1;
            continue;
        }
        defer _ = mlx.mlx_array_free(v4);
        // Per-head RMSNorm over head_dim, THEN rope — that order is the
        // reference's fused kernel, and swapping it changes the result.
        const nw = if (i == 0) aw.q_norm else aw.k_norm;
        const normed = try rmsNormLast(v4, nw, cfg.qk_norm_eps, s);
        if (rope) |rp| {
            defer _ = mlx.mlx_array_free(normed);
    qkvn[i] = try applyRopePub(normed, rp, half, hd, s);
        } else {
            qkvn[i] = normed;
        }
        built += 1;
    }
    defer for (&qkvn) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    // [1,S,H,hd] -> [1,H,S,hd] for SDPA
    var t: [3]mlx.mlx_array = undefined;
    for (0..3) |i| {
        const tr = try transpose(qkvn[i], &[_]c_int{ 0, 2, 1, 3 }, s);
        defer _ = mlx.mlx_array_free(tr);
        t[i] = try contig(tr, s);
    }
    defer for (&t) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    const scale: f32 = 1.0 / @sqrt(@as(f32, @floatFromInt(cfg.attention_head_dim)));
    var attn = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(attn);
    const null_a = mlx.mlx_array{ .ctx = null };
    try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&attn, t[0], t[1], t[2], scale, "", null_a, null_a, s));

    // [1,H,S,hd] -> [S, inner]
    const back = try transpose(attn, &[_]c_int{ 0, 2, 1, 3 }, s);
    defer _ = mlx.mlx_array_free(back);
    const bc = try contig(back, s);
    defer _ = mlx.mlx_array_free(bc);
    const flat = try reshape(bc, &[_]c_int{ n, h * hd }, s);
    defer _ = mlx.mlx_array_free(flat);
    return aw.out.forward(flat, null, s);
}

/// fc1 emits gate and up FUSED as [S, 2*ffn]; SwiGLU is silu(gate) * up.
fn mlpForward(mw: *const MlpW, x: mlx.mlx_array, s: S) !mlx.mlx_array {
    const y = try mw.fc1.forward(x, null, s);
    defer _ = mlx.mlx_array_free(y);
    var halves: [2]mlx.mlx_array = undefined;
    try splitEqual(y, 2, 1, &halves, s);
    defer for (&halves) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };
    const g = try siluA(halves[0], s);
    defer _ = mlx.mlx_array_free(g);
    const act = try mulA(g, halves[1], s);
    defer _ = mlx.mlx_array_free(act);
    return mw.fc2.forward(act, null, s);
}

// ── Modulation over packed segments ─────────────────────────────────────────

/// A contiguous run of rows sharing one AdaLN modulation row.
pub const ModRun = struct { start: u32, end: u32, mod_row: u32 };

/// `h[a:b] = h[a:b] * (1 + scale[row]) + shift[row]`, applied per run.
///
/// Done by slicing rather than gathering: a gather would materialize
/// [S, hidden] per modulation tensor (81 MB each at the dev shape, six per
/// block), while the runs number a handful.
fn modScaleShift(h: mlx.mlx_array, shift: mlx.mlx_array, scale: mlx.mlx_array, runs: []const ModRun, a: std.mem.Allocator, s: S) !mlx.mlx_array {
    var pieces = try a.alloc(mlx.mlx_array, runs.len);
    defer a.free(pieces);
    var built: usize = 0;
    errdefer for (pieces[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    const one = try scalarLike(1.0, h, s);
    defer _ = mlx.mlx_array_free(one);

    for (runs, 0..) |r, i| {
        const seg = try sliceRows(h, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(seg);
        const sc = try sliceRows(scale, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(sc);
        const sh = try sliceRows(shift, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(sh);
        const sc1 = try addA(sc, one, s);
        defer _ = mlx.mlx_array_free(sc1);
        const m = try mulA(seg, sc1, s);
        defer _ = mlx.mlx_array_free(m);
        pieces[i] = try addA(m, sh, s);
        built += 1;
    }
    defer for (pieces) |p| {
        _ = mlx.mlx_array_free(p);
    };
    return concat(pieces, 0, s);
}

/// `x[a:b] += other[a:b] * gate[row]`, applied per run.
fn modGate(x: mlx.mlx_array, gate: mlx.mlx_array, other: mlx.mlx_array, runs: []const ModRun, a: std.mem.Allocator, s: S) !mlx.mlx_array {
    var pieces = try a.alloc(mlx.mlx_array, runs.len);
    defer a.free(pieces);
    var built: usize = 0;
    errdefer for (pieces[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    for (runs, 0..) |r, i| {
        const xs = try sliceRows(x, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(xs);
        const os = try sliceRows(other, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(os);
        const g = try sliceRows(gate, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(g);
        const m = try mulA(os, g, s);
        defer _ = mlx.mlx_array_free(m);
        pieces[i] = try addA(xs, m, s);
        built += 1;
    }
    defer for (pieces) |p| {
        _ = mlx.mlx_array_free(p);
    };
    return concat(pieces, 0, s);
}

