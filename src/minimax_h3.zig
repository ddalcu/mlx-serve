/// libc getenv, matching generate.zig's allocator-free env idiom.
fn envStr(name: [:0]const u8) ?[]const u8 {
    const raw = std.c.getenv(name.ptr) orelse return null;
    const slice = std.mem.sliceTo(raw, 0);
    return if (slice.len == 0) null else slice;
}

fn envU32(name: [:0]const u8, dflt: u32) u32 {
    const v = envStr(name) orelse return dflt;
    return std.fmt.parseInt(u32, v, 10) catch dflt;
}

fn allFinite(x: mlx.mlx_array, s: S) !bool {
    var isf = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(isf);
    try mlx.check(mlx.mlx_isfinite(&isf, x, s));
    var allv = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(allv);
    try mlx.check(mlx.mlx_all(&allv, isf, false, s));
    try mlx.check(mlx.mlx_array_eval(allv));
    var b: bool = false;
    try mlx.check(mlx.mlx_array_item_bool(&b, allv));
    return b;
}

/// [-1,1] pixels -> 8-bit RGB frames on disk (raw + PNG).
fn writeFrames(a: std.mem.Allocator, io: std.Io, res: *const GenResult, out_dir: []const u8, s: S) !void {
    const png = @import("png.zig");
    // [1,3,F,H,W] -> [F,H,W,3] u8
    const p = try transpose(res.pixels, &[_]c_int{ 0, 2, 3, 4, 1 }, s);
    defer _ = mlx.mlx_array_free(p);
    const pc = try contig(p, s);
    defer _ = mlx.mlx_array_free(pc);
    const half = try scalarLike(0.5, pc, s);
    defer _ = mlx.mlx_array_free(half);
    const shifted = try addA(pc, try oneLike(pc, s), s);
    defer _ = mlx.mlx_array_free(shifted);
    const unit = try mulA(shifted, half, s);
    defer _ = mlx.mlx_array_free(unit);
    const c255 = try scalarLike(255.0, unit, s);
    defer _ = mlx.mlx_array_free(c255);
    const scaled = try mulA(unit, c255, s);
    defer _ = mlx.mlx_array_free(scaled);
    const u8a = try astype(scaled, mlx.mlx_dtype.uint8, s);
    defer _ = mlx.mlx_array_free(u8a);
    try mlx.check(mlx.mlx_array_eval(u8a));

    const n = res.frame_count * res.height * res.width * 3;
    const raw = mlx.mlx_array_data_uint8(u8a) orelse return error.NoPixelData;

    std.Io.Dir.cwd().createDirPath(io, out_dir) catch {};
    var d = try std.Io.Dir.cwd().openDir(io, out_dir, .{});
    defer d.close(io);

    const frame_bytes = res.height * res.width * 3;
    for (0..res.frame_count) |f| {
        const slice = raw[f * frame_bytes ..][0..frame_bytes];
        const bytes = try png.encodeRgb(a, slice, res.width, res.height);
        defer a.free(bytes);
        const name = try std.fmt.allocPrint(a, "frame_{d:0>4}.png", .{f});
        defer a.free(name);
        var fh = try d.createFile(io, name, .{});
        defer fh.close(io);
        var wbuf: [4096]u8 = undefined;
        var w = fh.writer(io, &wbuf);
        try w.interface.writeAll(bytes);
        try w.interface.flush();
    }
    _ = n;
}

fn oneLike(like: mlx.mlx_array, s: S) !mlx.mlx_array {
    return scalarLike(1.0, like, s);
}

fn absMax(x: mlx.mlx_array, s: S) !f32 {
    var ab = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(ab);
    try mlx.check(mlx.mlx_abs(&ab, x, s));
    var mx = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(mx);
    try mlx.check(mlx.mlx_max(&mx, ab, false, s));
    try mlx.check(mlx.mlx_array_eval(mx));
    var v: f32 = 0;
    try mlx.check(mlx.mlx_array_item_float32(&v, mx));
    return v;
}

/// Stereo [2, L] f32 -> interleaved 16-bit WAV at 32 kHz.
fn writeWav(a: std.mem.Allocator, io: std.Io, wave: mlx.mlx_array, out_dir: []const u8, s: S) !void {
    const wav = @import("wav.zig");
    const audio_mod = @import("minimax_h3_audio.zig");
    // [2, L] -> [L, 2] interleaved, which is what encodePcm16 expects.
    const t = try transpose(wave, &[_]c_int{ 1, 0 }, s);
    defer _ = mlx.mlx_array_free(t);
    const tc = try contig(t, s);
    defer _ = mlx.mlx_array_free(tc);
    const f = try astype(tc, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(f);
    try mlx.check(mlx.mlx_array_eval(f));
    const n: usize = @intCast(mlx.mlx_array_size(f));
    const raw = mlx.mlx_array_data_float32(f) orelse return error.NoAudioData;
    const bytes = try wav.encodePcm16(a, raw[0..n], audio_mod.SAMPLE_RATE, 2);
    defer a.free(bytes);

    var d = try std.Io.Dir.cwd().openDir(io, out_dir, .{});
    defer d.close(io);
    var fh = try d.createFile(io, "audio.wav", .{});
    defer fh.close(io);
    var wbuf: [4096]u8 = undefined;
    var w = fh.writer(io, &wbuf);
    try w.interface.writeAll(bytes);
    try w.interface.flush();
}

