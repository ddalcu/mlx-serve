    // fl2va: the keyframe rows pin near 1 via the visual aug, adding a third
    // distinct timestep — the row the AdaLN reshape must have space for.
    var l2 = try PackedLayout.init(a, 512, 17, 30, 54, 93, &.{.first}, 56);
    defer l2.deinit();
    var p2 = try buildTimestepPlan(a, &l2, 0.5, SIGMA_SHIFT_VIDEO, SIGMA_SHIFT_AUDIO, .{});
    defer p2.deinit();
    try testing.expectEqual(@as(usize, 3), p2.n_unique);
    try testing.expectApproxEqAbs(VISUAL_COND_TIMESTEP, p2.unique_t[2], 1e-12);
    // The cond segment carries the VIDEO modality tag but the condition
    // timestep — mixing those up modulates clean rows as if they were noisy.
    const cond_run = p2.runs[1];
    try testing.expectEqual(SegmentKind.cond, l2.segments[1].kind);
    try testing.expectEqual(@as(u32, 2 * 3 + 0), cond_run.mod_row);

    // Every run must address a row the AdaLN output actually has.
    for (p2.runs) |r| try testing.expect(r.mod_row < p2.n_unique * 3);

    // Runs tile the sequence exactly — a gap would leave rows unmodulated and
    // an overlap would modulate them twice.
    var cursor: u32 = 0;
    for (p2.runs) |r| {
        try testing.expectEqual(cursor, r.start);
        cursor = r.end;
    }
    try testing.expectEqual(l2.seq_len, cursor);
}

/// Cosine similarity between two arrays, with a FINITENESS check first.
/// `NaN > threshold` is false, so an all-NaN candidate scores a perfect 0 error
/// and sails through any comparison that diffs before it checks.
fn cosineSim(a_arr: mlx.mlx_array, b_arr: mlx.mlx_array, s: S) !f32 {
    const af = try astype(a_arr, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(af);
    const bf = try astype(b_arr, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(bf);
    const n: c_int = @intCast(mlx.mlx_array_size(af));
    const a1 = try reshape(af, &[_]c_int{n}, s);
    defer _ = mlx.mlx_array_free(a1);
    const b1 = try reshape(bf, &[_]c_int{n}, s);
    defer _ = mlx.mlx_array_free(b1);

    const dot = try sumAll(try mulOwned(a1, b1, s), s);
    const na = try sumAll(try mulOwned(a1, a1, s), s);
    const nb = try sumAll(try mulOwned(b1, b1, s), s);
    if (!std.math.isFinite(dot) or !std.math.isFinite(na) or !std.math.isFinite(nb)) return std.math.nan(f32);
    if (na <= 0 or nb <= 0) return std.math.nan(f32);
    return dot / (@sqrt(na) * @sqrt(nb));
}

fn mulOwned(a_arr: mlx.mlx_array, b_arr: mlx.mlx_array, s: S) !mlx.mlx_array {
    return mulA(a_arr, b_arr, s);
}

fn sumAll(x: mlx.mlx_array, s: S) !f32 {
    defer _ = mlx.mlx_array_free(x);
    var o = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o);
    try mlx.check(mlx.mlx_sum(&o, x, false, s));
    try mlx.check(mlx.mlx_array_eval(o));
    var v: f32 = 0;
    try mlx.check(mlx.mlx_array_item_float32(&v, o));
    return v;
}

test "minimax h3: DiT block matches the reference transcription" {
    // Hermetic: a 1.8 MB toy-geometry fixture with synthetic weights, from
    // tests/dump_minimax_h3_fixtures.py. See that file's header for exactly
    // what this does and does not prove — the reference's own block calls
    // comfy_kitchen CUDA kernels that cannot run here, so the oracle is an
    // independently written transcription, not the reference executing.
    const a = testing.allocator;
    const s = mlx.gpuStream();

    var w = model_mod.loadWeightsSingleFile(a, "src/fixtures/minimax_h3_dit.safetensors") catch |e| {
        std.debug.print("skip: fixture unreadable ({any})\n", .{e});
        return error.SkipZigTest;
    };
    defer w.deinit();

    // Toy geometry, mirroring TOY in the dumper. Kept explicit rather than read
    // from metadata so a fixture regenerated at a different size fails loudly
    // instead of silently testing a different model.
    const cfg = Config{
        .hidden_size = 256,
        .num_attention_heads = 4,
        .attention_head_dim = 32,
        .ffn_hidden_size = 128,
        .time_embed_dim = 32,
        .timestep_input_dim = 32,
        .rope_inv_freq_len = 4,
    };
    try testing.expectEqual(@as(u32, 24), cfg.rotDim());
    try testing.expect(cfg.rotDim() < cfg.attention_head_dim); // partial rope

    const f32t = mlx.mlx_dtype.float32;
    var attn = try AttnW.load(&w, a, "attn", cfg, f32t, s);
    defer attn.deinit();
    var mlp_w = try MlpW.load(&w, a, "mlp", cfg, f32t, s);
    defer mlp_w.deinit();
    var adaln = try AdalnW.load(&w, a, "adaln_proj", cfg, 6, 3, f32t, s);
    defer adaln.deinit();
    const norm1 = try ownWeight(&w, "norm1.weight");
    defer _ = mlx.mlx_array_free(norm1);
    const norm2 = try ownWeight(&w, "norm2.weight");
    defer _ = mlx.mlx_array_free(norm2);

    const h_in = try ownWeight(&w, "x.h_in");
    defer _ = mlx.mlx_array_free(h_in);
    const seq: c_int = @intCast(mlx.getShape(h_in)[0]);

    // Rope tables come from the fixture's own cos/sin so this checks the
    // APPLICATION (pairing + pass-through tail), not the table build, which
    // the layout fixture already pins.
    const rc = try ownWeight(&w, "x.rope_cos");
    defer _ = mlx.mlx_array_free(rc);
    const rs = try ownWeight(&w, "x.rope_sin");
    defer _ = mlx.mlx_array_free(rs);
    const half: c_int = @intCast(cfg.rotDim() / 2);
    const rc4 = try reshape(rc, &[_]c_int{ 1, seq, 1, half }, s);
    const rs4 = try reshape(rs, &[_]c_int{ 1, seq, 1, half }, s);
    var rope = RopeTables{ .cos = rc4, .sin = rs4 };
    defer rope.deinit();

    // [1/4] attention, including per-head RMSNorm then partial rope
    {
        const attn_in = try ownWeight(&w, "x.attn_in");
        defer _ = mlx.mlx_array_free(attn_in);
        const want = try ownWeight(&w, "x.attn_out");
        defer _ = mlx.mlx_array_free(want);
        const got = try attnForward(&attn, attn_in, cfg, rope, s);
        defer _ = mlx.mlx_array_free(got);
        const cos_v = try cosineSim(got, want, s);
        try testing.expect(std.math.isFinite(cos_v));
        if (cos_v < 0.9999) std.debug.print("attn cos={d:.6}\n", .{cos_v});
        try testing.expect(cos_v > 0.9999);
    }

    // [2/4] SwiGLU MLP — pins that gate is the FIRST half of the fused fc1
    {
        const attn_in = try ownWeight(&w, "x.attn_in");
        defer _ = mlx.mlx_array_free(attn_in);
        const want = try ownWeight(&w, "x.mlp_out");
        defer _ = mlx.mlx_array_free(want);
        const got = try mlpForward(&mlp_w, attn_in, s);
        defer _ = mlx.mlx_array_free(got);
        const cos_v = try cosineSim(got, want, s);
        try testing.expect(std.math.isFinite(cos_v));
        if (cos_v < 0.9999) std.debug.print("mlp cos={d:.6}\n", .{cos_v});
        try testing.expect(cos_v > 0.9999);
    }

    // [3/4] the whole block, with three runs on three different mod rows
    {
        const runs_arr = try ownWeight(&w, "x.runs");
        defer _ = mlx.mlx_array_free(runs_arr);
        try mlx.check(mlx.mlx_array_eval(runs_arr));
        const n_runs: usize = @intCast(mlx.getShape(runs_arr)[0]);
        const raw = mlx.mlx_array_data_int32(runs_arr) orelse return error.NoRunData;
        var runs = try a.alloc(ModRun, n_runs);
        defer a.free(runs);
        for (0..n_runs) |i| runs[i] = .{
            .start = @intCast(raw[i * 3 + 0]),
            .end = @intCast(raw[i * 3 + 1]),
            .mod_row = @intCast(raw[i * 3 + 2]),
        };

        const t_emb = try ownWeight(&w, "x.t_emb");
        defer _ = mlx.mlx_array_free(t_emb);
        var mods: [6]mlx.mlx_array = undefined;
        try adaln.forward(t_emb, cfg, true, &mods, s);
        defer for (&mods) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };

        const n1 = try rmsNormLast(h_in, norm1, cfg.norm_eps, s);
        defer _ = mlx.mlx_array_free(n1);
        const m1 = try modScaleShift(n1, mods[0], mods[1], runs, a, s);
        defer _ = mlx.mlx_array_free(m1);
        const at = try attnForward(&attn, m1, cfg, rope, s);
        defer _ = mlx.mlx_array_free(at);
        const h1 = try modGate(h_in, mods[2], at, runs, a, s);
        defer _ = mlx.mlx_array_free(h1);
        const n2 = try rmsNormLast(h1, norm2, cfg.norm_eps, s);
        defer _ = mlx.mlx_array_free(n2);
        const m2 = try modScaleShift(n2, mods[3], mods[4], runs, a, s);
        defer _ = mlx.mlx_array_free(m2);
        const mo = try mlpForward(&mlp_w, m2, s);
        defer _ = mlx.mlx_array_free(mo);
        const got = try modGate(h1, mods[5], mo, runs, a, s);
        defer _ = mlx.mlx_array_free(got);

        const want = try ownWeight(&w, "x.h_out");
        defer _ = mlx.mlx_array_free(want);
        const cos_v = try cosineSim(got, want, s);
        try testing.expect(std.math.isFinite(cos_v));
        if (cos_v < 0.9999) std.debug.print("block cos={d:.6}\n", .{cos_v});
        try testing.expect(cos_v > 0.9999);
    }

    // [4/4] the rope tail must be a PASS-THROUGH. Rotating the full head is the
    // classic silent slip: it still runs, still produces plausible output, and
    // the cosine above would catch it only because the fixture happens to use a
    // partial width — so assert the invariant directly.
    {
        const x = try ownWeight(&w, "x.attn_in");
        defer _ = mlx.mlx_array_free(x);
        const hd: c_int = @intCast(cfg.attention_head_dim);
        const heads: c_int = @intCast(cfg.num_attention_heads);
        const x4 = try reshape(x, &[_]c_int{ 1, seq, heads, @divExact(@as(c_int, @intCast(cfg.hidden_size)), heads) }, s);
        defer _ = mlx.mlx_array_free(x4);
        _ = hd;
        // Build a [1,seq,heads,head_dim] probe of ones; after rope its tail
        // dims must still be exactly 1.
        const probe_shape = [_]c_int{ 1, seq, heads, @intCast(cfg.attention_head_dim) };
        var ones = mlx.mlx_array_new();
        defer _ = mlx.mlx_array_free(ones);
        try mlx.check(mlx.mlx_ones(&ones, &probe_shape, 4, mlx.mlx_dtype.float32, s));
        const rotated = try applyRopePub(ones, rope, half, @intCast(cfg.attention_head_dim), s);
        defer _ = mlx.mlx_array_free(rotated);
        const tail = try sliceLast4(rotated, @intCast(cfg.rotDim()), @intCast(cfg.attention_head_dim), s);
        defer _ = mlx.mlx_array_free(tail);
        const tail_ones = try sliceLast4(ones, @intCast(cfg.rotDim()), @intCast(cfg.attention_head_dim), s);
        defer _ = mlx.mlx_array_free(tail_ones);
        const cos_v = try cosineSim(tail, tail_ones, s);
        try testing.expect(std.math.isFinite(cos_v));
        try testing.expectApproxEqAbs(@as(f32, 1.0), cos_v, 1e-6);
        // And the rotated part must actually have MOVED, or "pass-through"
        // would be trivially satisfied by a no-op rope.
        const head = try sliceLast4(rotated, 0, @intCast(cfg.rotDim()), s);
        defer _ = mlx.mlx_array_free(head);
        const head_ones = try sliceLast4(ones, 0, @intCast(cfg.rotDim()), s);
        defer _ = mlx.mlx_array_free(head_ones);
        const moved = try cosineSim(head, head_ones, s);
        try testing.expect(std.math.isFinite(moved));
        try testing.expect(moved < 0.999);
    }
}

