        try testing.expect(cos_v > 0.9999);
    }

    // [4/4] the rope tail must be a PASS-THROUGH. Rotating the full head is the
    // classic silent slip: it still runs, still produces plausible output, and
    // the cosine above would catch it only because the fixture happens to use a
