// ── Constants (asserted against the reference in the fixture test) ───────────

/// Source frames represented by latent frame k, cycling on k % 5. The VAE is
/// f16t4d24 on average but NOT uniform: 1 + 4*4 = 17 frames per 5 latents.
pub const FRAME_PER_TOKEN = [5]u32{ 1, 4, 4, 4, 4 };
pub const FRAME_RESCALE: f64 = 5.0 / 3.0;
pub const VISUAL_COND_TIMESTEP: f64 = 0.999;
pub const AUDIO_COND_TIMESTEP: f64 = 1.0;

pub const CANVAS_MULTIPLE: u32 = 32;
pub const BASE_SHORT_EDGE: u32 = 768;
pub const MAX_PIXELS: u32 = 768 * 1344;
pub const FPS: u32 = 24;
pub const AUDIO_LATENT_FPS: u32 = 40;

/// Defaults from the checkpoint's `model_index.json` `sigma_shift_scales`.
pub const SIGMA_SHIFT_VIDEO: f64 = 12.0;
pub const SIGMA_SHIFT_AUDIO: f64 = 3.0;

/// Spatial compression: VAE 16x, then the DiT's 2x2 patch → 32x effective.
pub const VAE_SPATIAL: u32 = 16;
pub const PATCH_H: u32 = 2;
pub const PATCH_W: u32 = 2;

// ── Frame ladder ────────────────────────────────────────────────────────────

/// Snap UP to the model's 17k+5 grid. 40 -> 56, 200 -> 209, 363 -> 379.
pub fn alignFrameCount(n: u32) u32 {
    var v = n;
    while (v % 17 != 5) v += 1;
    return v;
}

/// Latent frames for an aligned source-frame count.
pub fn videoLatentT(frame_count: u32) u32 {
    if (frame_count <= 5) return 2;
    return ((frame_count - 5) / 17) * 5 + 2;
}

pub const TemporalShape = struct { frame_count: u32, latent_t: u32, audio_t: u32 };

/// Aligned frame count + its latent-frame and audio-latent counts.
pub fn temporalShape(length: u32) TemporalShape {
    const frame_count = alignFrameCount(@max(5, length));
    const fc: f64 = @floatFromInt(frame_count);
    // audio_t = round(frame_count / 24 * 40) = round(frame_count * 5 / 3). The
    // reference uses Python's banker's rounding, but frame_count*5/3 can only
    // have fraction 0, 1/3 or 2/3 — never exactly 1/2 — so the two agree and
    // plain rounding is safe here. adaptCanvas is NOT so lucky; see below.
    const audio_t = @round(fc / @as(f64, @floatFromInt(FPS)) * @as(f64, @floatFromInt(AUDIO_LATENT_FPS)));
    return .{
        .frame_count = frame_count,
        .latent_t = videoLatentT(frame_count),
        .audio_t = @intFromFloat(audio_t),
    };
}

// ── Canvas ──────────────────────────────────────────────────────────────────

pub const Canvas = struct { w: u32, h: u32 };

/// 768-short-edge canvas under the 768*1344 area cap, each axis rounded to 32.
/// Note this UPSCALES a small input (640x480 -> 1024x768): it normalizes to the
/// model's native short edge. Applied to ref2va REFERENCE videos only — the
/// target canvas comes straight from the request.
pub fn adaptCanvas(w: u32, h: u32) Canvas {
    const fw: f64 = @floatFromInt(w);
    const fh: f64 = @floatFromInt(h);
    const ratio = fw / fh;
    const base: f64 = @floatFromInt(BASE_SHORT_EDGE);
    var nom_w: f64 = if (ratio >= 1.0) base * ratio else base;
    var nom_h: f64 = if (ratio >= 1.0) base else base / ratio;

    const cap: f64 = @floatFromInt(MAX_PIXELS);
    if (nom_w * nom_h > cap) {
        const s = @sqrt(cap / (nom_w * nom_h));
        nom_w *= s;
        nom_h *= s;
    }
    const m: f64 = @floatFromInt(CANVAS_MULTIPLE);
    return .{
        .w = @max(CANVAS_MULTIPLE, @as(u32, @intFromFloat(roundHalfEven(nom_w / m) * m))),
        .h = @max(CANVAS_MULTIPLE, @as(u32, @intFromFloat(roundHalfEven(nom_h / m) * m))),
    };
}

/// Python's `round`, i.e. half-to-even — NOT Zig's `@round`, which rounds half
/// away from zero. `nom_w / 32` can land exactly on .5 (a 1360-wide nominal
/// canvas gives 42.5), and there the two disagree by a whole 32-pixel step.
/// Inputs here are non-negative, which is what keeps this simple.
fn roundHalfEven(x: f64) f64 {
    const fl = @floor(x);
    const frac = x - fl;
    if (frac > 0.5) return fl + 1;
    if (frac < 0.5) return fl;
    return if (@mod(fl, 2.0) == 0.0) fl else fl + 1;
}

// ── Dual sigma schedule ─────────────────────────────────────────────────────

/// Map a sigma from one shifted schedule to another through the shared base
/// grid: invert sigma = s*b/(1+(s-1)*b), then re-apply the other shift.
pub fn timeShiftSigma(sigma: f64, from_shift: f64, to_shift: f64) f64 {
    const base = shiftToBase(sigma, from_shift);
    return to_shift * base / (1.0 + (to_shift - 1.0) * base);
}

/// Invert sigma = shift*b / (1 + (shift-1)*b) back to the shared base grid.
fn shiftToBase(sigma: f64, shift: f64) f64 {
    return sigma / (shift + sigma * (1.0 - shift));
}

/// d(sigma_to)/d(sigma_from) at the same base-grid point. The audio velocity is
/// scaled by this so the flat ODE the sampler integrates on the VIDEO schedule
/// equals the audio stream's true ODE on its own. Getting it wrong desyncs the
/// soundtrack instead of erroring.
pub fn timeShiftSlope(sigma: f64, from_shift: f64, to_shift: f64) f64 {
    const base = shiftToBase(sigma, from_shift);
    const num = 1.0 + (from_shift - 1.0) * base;
    const den = 1.0 + (to_shift - 1.0) * base;
    return (to_shift * num * num) / (from_shift * den * den);
}

// ── Position grids ──────────────────────────────────────────────────────────

/// Area-normalized coordinates along one spatial axis: n = dim/patch values of
/// (arange(n) * ratio/n + (1-ratio)/2) * 32, ratio = dim / sqrt(area).
/// Caller owns the returned slice.
pub fn axisFromSqrtArea(allocator: std.mem.Allocator, dim: u32, patch: u32, sqrt_area: f64) ![]f64 {
    const n = dim / patch;
    const out = try allocator.alloc(f64, n);
    errdefer allocator.free(out);
    const ratio = @as(f64, @floatFromInt(dim)) / sqrt_area;
    const step = ratio / @as(f64, @floatFromInt(n));
    const start = (1.0 - ratio) / 2.0;
    for (out, 0..) |*v, i| v.* = (@as(f64, @floatFromInt(i)) * step + start) * 32.0;
    return out;
}

/// Temporal span of latent frame k, in the grid's units.
pub fn videoTSpan(k: usize) f64 {
    return FRAME_RESCALE * @as(f64, @floatFromInt(FRAME_PER_TOKEN[k % FRAME_PER_TOKEN.len]));
}

/// Exclusive cumulative sum of the first n spans, offset by `origin`.
/// Caller owns the returned slice.
pub fn videoTGrid(allocator: std.mem.Allocator, n: u32, origin: f64) ![]f64 {
    const out = try allocator.alloc(f64, n);
    errdefer allocator.free(out);
    var acc: f64 = origin;
    for (out, 0..) |*v, i| {
        v.* = acc;
        acc += videoTSpan(i);
    }
    return out;
}

// ── Packed layout ───────────────────────────────────────────────────────────

pub const SegmentKind = enum {
    text,
    cond,
    ref_img,
    ref_audio,
    audio,
    video,

    pub fn fromString(s: []const u8) ?SegmentKind {
        inline for (@typeInfo(SegmentKind).@"enum".field_names) |n| {
            if (std.mem.eql(u8, s, n)) return @field(SegmentKind, n);
        }
        return null;
    }

    /// Which embedding stream feeds this segment's rows.
    pub fn stream(self: SegmentKind) enum { text, video, audio } {
        return switch (self) {
            .text => .text,
            .cond, .ref_img, .video => .video,
            .ref_audio, .audio => .audio,
        };
    }

    /// AdaLN modality tag. Three modalities: video 0, text 1, audio 2. The mod
    /// row is `t_row * 3 + tag`, so a wrong tag silently modulates a stream with
    /// another stream's statistics.
    pub fn modalityTag(self: SegmentKind) u32 {
        return switch (self) {
            .video, .cond, .ref_img => 0,
            .text => 1,
            .audio, .ref_audio => 2,
        };
    }
};

pub const Segment = struct { start: u32, end: u32, kind: SegmentKind };

/// Where a keyframe is anchored in the SOURCE frame timeline. Only the first
/// and last frames are anchorable — the reference raises on anything else, and
/// so do we (an interior anchor has no defined temporal coordinate).
pub const KeyframeAnchor = enum { first, last };

/// Static packed-sequence structure for one shape + conditioning signature.
///
/// Layout is `[text | cond... | audio | video]`, and the target audio/video are
/// ALWAYS the last two segments — the final layer slices them by that promise.
pub const PackedLayout = struct {
    allocator: std.mem.Allocator,
    seq_len: u32,
    segments: []Segment,
    /// [seq_len * 3] row-major (t, h, w). f64 because the reference builds the
    /// grid in float64 and only casts to f32 when computing RoPE angles;
    /// accumulating the temporal cumsum in f32 drifts at long durations.
    position_ids: []f64,
    /// Per video-stream row, in packed order: true = a target row that gets
    /// denoised, false = a condition row that is re-injected every step.
    img_update: []bool,
    audio_update: []bool,
    text_len: u32,
    latent_t: u32,
    latent_h: u32,
    latent_w: u32,
    audio_t: u32,

    pub fn init(
        allocator: std.mem.Allocator,
        text_len: u32,
        latent_t: u32,
        latent_h: u32,
        latent_w: u32,
        audio_t: u32,
        keyframes: []const KeyframeAnchor,
        frame_count: u32,
    ) !PackedLayout {
        const area = @sqrt(@as(f64, @floatFromInt(latent_h)) * @as(f64, @floatFromInt(latent_w)));
        const h_axis = try axisFromSqrtArea(allocator, latent_h, PATCH_H, area);
        defer allocator.free(h_axis);
        const w_axis = try axisFromSqrtArea(allocator, latent_w, PATCH_W, area);
        defer allocator.free(w_axis);
        const frame_rows: u32 = @intCast(h_axis.len * w_axis.len);

        const n_cond: u32 = @intCast(keyframes.len);
        const n_audio_rows = audio_t * 2;
        const n_video_rows = latent_t * frame_rows;
        const seq_len = text_len + n_cond * frame_rows + n_audio_rows + n_video_rows;

        var segments = try std.ArrayList(Segment).initCapacity(allocator, 3 + n_cond);
        errdefer segments.deinit(allocator);
        const position_ids = try allocator.alloc(f64, @as(usize, seq_len) * 3);
        errdefer allocator.free(position_ids);
        const img_update = try allocator.alloc(bool, n_cond * frame_rows + n_video_rows);
        errdefer allocator.free(img_update);
        const audio_update = try allocator.alloc(bool, n_audio_rows);
        errdefer allocator.free(audio_update);

        @memset(position_ids, 0);

        var row: u32 = 0;
        var img_row: u32 = 0;

        // text: t = 0..text_len-1, h = w = 0
        try segments.append(allocator, .{ .start = 0, .end = text_len, .kind = .text });
        for (0..text_len) |i| position_ids[(row + i) * 3] = @floatFromInt(i);
        row += text_len;

        // The cursor the target streams share. Without refs it stays at
        // text_len; the ref2va branch advances it per reference block.
        const cursor: f64 = @floatFromInt(text_len);

        // fl2va keyframe condition rows, sharing the target spatial grid.
        for (keyframes) |anchor| {
            const cond_t: f64 = switch (anchor) {
                .first => cursor,
                // The last keyframe sits at the START of the final latent
                // frame's span, i.e. one FRAME_RESCALE unit back from the end.
                .last => blk: {
                    var spans: f64 = 0;
                    for (0..latent_t) |k| spans += videoTSpan(k);
                    break :blk cursor + spans - FRAME_RESCALE;
                },
            };
            try segments.append(allocator, .{ .start = row, .end = row + frame_rows, .kind = .cond });
            writeFrameGrid(position_ids, row, cond_t, h_axis, w_axis);
            for (0..frame_rows) |_| {
                img_update[img_row] = false; // condition rows are never denoised
                img_row += 1;
            }
            row += frame_rows;
        }
        _ = frame_count; // only the anchor matters; kept for call-site symmetry

        // Target audio, then target video — always the last two segments.
        try segments.append(allocator, .{ .start = row, .end = row + n_audio_rows, .kind = .audio });
        writeAudioGrid(position_ids, row, cursor, audio_t, w_axis[0], w_axis[w_axis.len - 1]);
        @memset(audio_update, true);
        row += n_audio_rows;

        try segments.append(allocator, .{ .start = row, .end = row + n_video_rows, .kind = .video });
        const t_grid = try videoTGrid(allocator, latent_t, cursor);
        defer allocator.free(t_grid);
        for (t_grid, 0..) |tv, f| {
            writeFrameGrid(position_ids, row + @as(u32, @intCast(f)) * frame_rows, tv, h_axis, w_axis);
        }
        for (0..n_video_rows) |_| {
            img_update[img_row] = true;
            img_row += 1;
        }
        row += n_video_rows;

        std.debug.assert(row == seq_len);
        return .{
            .allocator = allocator,
            .seq_len = seq_len,
            .segments = try segments.toOwnedSlice(allocator),
            .position_ids = position_ids,
            .img_update = img_update,
            .audio_update = audio_update,
            .text_len = text_len,
            .latent_t = latent_t,
            .latent_h = latent_h,
            .latent_w = latent_w,
            .audio_t = audio_t,
        };
    }

    pub fn deinit(self: *PackedLayout) void {
        self.allocator.free(self.segments);
        self.allocator.free(self.position_ids);
        self.allocator.free(self.img_update);
        self.allocator.free(self.audio_update);
        self.* = undefined;
    }

    /// The target video segment — the final layer's slice. Last segment by
    /// construction.
    pub fn videoSegment(self: *const PackedLayout) Segment {
        return self.segments[self.segments.len - 1];
    }

    /// The target audio segment — second to last by construction.
    pub fn audioSegment(self: *const PackedLayout) Segment {
        return self.segments[self.segments.len - 2];
    }
};

/// One latent frame's rows: t fixed, (h, w) the row-major meshgrid of the axes.
fn writeFrameGrid(pos: []f64, row: u32, t: f64, h_axis: []const f64, w_axis: []const f64) void {
    var i: usize = row;
    for (h_axis) |hv| {
        for (w_axis) |wv| {
            pos[i * 3 + 0] = t;
            pos[i * 3 + 1] = hv;
            pos[i * 3 + 2] = wv;
            i += 1;
        }
    }
}

/// Stereo audio rows, CHANNEL-MAJOR: t advances per latent step, h stays 0, and
/// w is pinned to the spatial grid's two extremes so the two channels occupy
/// distinct positions rather than colliding.
fn writeAudioGrid(pos: []f64, row: u32, cursor: f64, audio_t: u32, w_low: f64, w_high: f64) void {
    for (0..audio_t) |i| {
        const t = cursor + @as(f64, @floatFromInt(i));
        const a = (row + i) * 3;
        pos[a + 0] = t;
        pos[a + 1] = 0;
        pos[a + 2] = w_low;
        const b = (row + audio_t + i) * 3;
        pos[b + 0] = t;
        pos[b + 1] = 0;
        pos[b + 2] = w_high;
    }
}

