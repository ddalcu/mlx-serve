fn ownWeight(w: *const Weights, key: []const u8) !mlx.mlx_array {
    const a = w.get(key) orelse {
        log.err("[minimax-h3] MISSING WEIGHT: {s}\n", .{key});
        return error.MissingMiniMaxH3Weight;
    };
    var o = mlx.mlx_array_new();
    try mlx.check(mlx.mlx_array_set(&o, a));
    return o;
}
fn ownWeightAs(w: *const Weights, a: std.mem.Allocator, prefix: []const u8, suffix: []const u8, dt: mlx.mlx_dtype, s: S) !mlx.mlx_array {
    const key = try std.fmt.allocPrint(a, "{s}{s}", .{ prefix, suffix });
    defer a.free(key);
    const raw = try ownWeight(w, key);
    defer _ = mlx.mlx_array_free(raw);
    return astype(raw, dt, s);
}
/// Dense linear stored [out, in]; used only for the checkpoint's fp32 islands,
/// which are small and never quantized.
fn denseLinear(x: mlx.mlx_array, w: mlx.mlx_array, bias: ?mlx.mlx_array, s: S) !mlx.mlx_array {
    const wt = try transpose(w, &[_]c_int{ 1, 0 }, s);
    defer _ = mlx.mlx_array_free(wt);
    const wc = try contig(wt, s);
    defer _ = mlx.mlx_array_free(wc);
    var o = mlx.mlx_array_new();
    try mlx.check(mlx.mlx_matmul(&o, x, wc, s));
    if (bias) |b| {
        defer _ = mlx.mlx_array_free(o);
        return addA(o, b, s);
    }
    return o;
}

