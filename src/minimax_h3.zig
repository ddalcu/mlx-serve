test "minimax h3: packed layout matches the reference segment table" {
    const a = testing.allocator;
    var parsed = try loadFixture(a);
    defer parsed.deinit();

    for (parsed.value.object.get("packed_layout").?.array.items) |item| {
        const o = item.object;
        const name = o.get("name").?.string;

        // The fixture's keyframe set is implied by its segment table: the
        // reference emits one "cond" segment per anchored keyframe, first then
        // last. Deriving it here keeps the test honest about what it feeds in.
        var anchors: [2]KeyframeAnchor = undefined;
        var n_anchors: usize = 0;
        for (o.get("segments").?.array.items) |seg| {
            if (std.mem.eql(u8, seg.array.items[2].string, "cond")) {
                anchors[n_anchors] = if (n_anchors == 0) .first else .last;
                n_anchors += 1;
            }
        }

