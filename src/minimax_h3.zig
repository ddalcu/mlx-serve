pub const MAX_UNIQUE_T = 4;

/// The distinct timesteps a forward needs, and the per-run modulation rows.
///
/// The reference derives these analytically rather than carrying a per-token
/// timestep tensor: text and video ride the video timestep, audio rides its own
/// shifted one, and condition rows pin near 1 (they are re-injected clean every
/// step, never denoised).
pub const TimestepPlan = struct {
    unique_t: [MAX_UNIQUE_T]f64,
    n_unique: usize,
    runs: []ModRun,
    allocator: std.mem.Allocator,

    pub fn deinit(self: *TimestepPlan) void {
        self.allocator.free(self.runs);
    }
};

pub const CondNoiseAug = struct {
    visual: f64 = VISUAL_COND_TIMESTEP,
    audio: f64 = AUDIO_COND_TIMESTEP,
};

pub fn buildTimestepPlan(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    sigma_v: f64,
    shift_v: f64,
    shift_a: f64,
    aug: CondNoiseAug,
) !TimestepPlan {
    const t_v = 1.0 - sigma_v;
    const t_a = 1.0 - timeShiftSigma(sigma_v, shift_v, shift_a);

    var uniq: [MAX_UNIQUE_T]f64 = undefined;
    var n: usize = 0;
    const add = struct {
        fn f(buf: *[MAX_UNIQUE_T]f64, cnt: *usize, v: f64) void {
            for (buf[0..cnt.*]) |e| if (e == v) return;
            buf[cnt.*] = v;
            cnt.* += 1;
        }
    }.f;

    var has_vis_cond = false;
    var has_aud_cond = false;
    for (layout.segments) |seg| switch (seg.kind) {
        .cond, .ref_img => has_vis_cond = true,
        .ref_audio => has_aud_cond = true,
        else => {},
    };
    add(&uniq, &n, t_v);
    add(&uniq, &n, t_a);
    if (has_vis_cond) add(&uniq, &n, @max(t_v, aug.visual));
    if (has_aud_cond) add(&uniq, &n, @max(t_a, aug.audio));
    std.mem.sort(f64, uniq[0..n], {}, std.sort.asc(f64));

    const rowOf = struct {
        fn f(buf: []const f64, v: f64) u32 {
            for (buf, 0..) |e, i| if (e == v) return @intCast(i);
            unreachable;
        }
    }.f;

    var runs = try allocator.alloc(ModRun, layout.segments.len);
    errdefer allocator.free(runs);
    for (layout.segments, 0..) |seg, i| {
        const t = switch (seg.kind) {
            .text, .video => t_v,
            .audio => t_a,
            .cond, .ref_img => @max(t_v, aug.visual),
            .ref_audio => @max(t_a, aug.audio),
        };
        // Row = t_row * modalities + tag. The `* 3` is the AdaLN reshape's
        // modality stride, not an arbitrary constant.
        runs[i] = .{
            .start = seg.start,
            .end = seg.end,
            .mod_row = rowOf(uniq[0..n], t) * 3 + seg.kind.modalityTag(),
        };
    }
    return .{ .unique_t = uniq, .n_unique = n, .runs = runs, .allocator = allocator };
}

// ── Model ───────────────────────────────────────────────────────────────────

pub const Model = struct {
    allocator: std.mem.Allocator,
    cfg: Config,
    dtype: mlx.mlx_dtype,

    video_patch_w: mlx.mlx_array, // fp32 island
    video_patch_b: mlx.mlx_array,
    audio_patch_w: mlx.mlx_array,
    audio_patch_b: mlx.mlx_array,
    condition_proj: MfLinear,
    condition_bias: mlx.mlx_array,

    te_in_w: mlx.mlx_array, // time embedder, fp32 island
    te_in_b: mlx.mlx_array,
    te_out_w: mlx.mlx_array,
    te_out_b: mlx.mlx_array,
    inv_freq: mlx.mlx_array,

    refiner: []RefinerBlockW,
    refiner_final_norm: mlx.mlx_array,
    blocks: []BlockW,

    final_norm: mlx.mlx_array,
    final_adaln: AdalnW,
    video_out_w: mlx.mlx_array, // fp32 island
    video_out_b: mlx.mlx_array,
    audio_out_w: mlx.mlx_array,
    audio_out_b: mlx.mlx_array,

    pub fn load(allocator: std.mem.Allocator, w: *const Weights, cfg: Config, dt: mlx.mlx_dtype, s: S) !Model {
        var m: Model = undefined;
        m.allocator = allocator;
        m.cfg = cfg;
        m.dtype = dt;

        const f32t = mlx.mlx_dtype.float32;
        // These stay fp32 because the CHECKPOINT stores them fp32 — the patch
        // projections and output heads are its dense islands, and narrowing
        // them is the MageFlow precision class.
        m.video_patch_w = try ownWeightAs(w, allocator, "video_patch_proj", ".weight", f32t, s);
        m.video_patch_b = try ownWeightAs(w, allocator, "video_patch_proj", ".bias", f32t, s);
        m.audio_patch_w = try ownWeightAs(w, allocator, "audio_patch_proj", ".weight", f32t, s);
        m.audio_patch_b = try ownWeightAs(w, allocator, "audio_patch_proj", ".bias", f32t, s);
        m.condition_proj = try MfLinear.load(w, allocator, "condition_proj", cfg.text_dim, dt, s);
        m.condition_bias = try ownWeightAs(w, allocator, "condition_proj", ".bias", dt, s);

        m.te_in_w = try ownWeightAs(w, allocator, "time_embedder.proj_in", ".weight", f32t, s);
        m.te_in_b = try ownWeightAs(w, allocator, "time_embedder.proj_in", ".bias", f32t, s);
        m.te_out_w = try ownWeightAs(w, allocator, "time_embedder.proj_out", ".weight", f32t, s);
        m.te_out_b = try ownWeightAs(w, allocator, "time_embedder.proj_out", ".bias", f32t, s);
        m.inv_freq = try ownWeightAs(w, allocator, "rope", ".inv_freq", f32t, s);

        m.refiner = try allocator.alloc(RefinerBlockW, cfg.token_refiner_num_layers);
        for (m.refiner, 0..) |*b, i| b.* = try RefinerBlockW.load(w, allocator, @intCast(i), cfg, dt, s);
        m.refiner_final_norm = try ownWeightAs(w, allocator, "token_refiner.final_norm", ".weight", dt, s);

        m.blocks = try allocator.alloc(BlockW, cfg.num_layers);
        for (m.blocks, 0..) |*b, i| b.* = try BlockW.load(w, allocator, @intCast(i), cfg, dt, s);

        m.final_norm = try ownWeightAs(w, allocator, "final_layer.norm", ".weight", dt, s);
        m.final_adaln = try AdalnW.load(w, allocator, "final_layer.adaln_proj", cfg, 2, 1, dt, s);
        m.video_out_w = try ownWeightAs(w, allocator, "final_layer.video_out", ".weight", f32t, s);
        m.video_out_b = try ownWeightAs(w, allocator, "final_layer.video_out", ".bias", f32t, s);
        m.audio_out_w = try ownWeightAs(w, allocator, "final_layer.audio_out", ".weight", f32t, s);
        m.audio_out_b = try ownWeightAs(w, allocator, "final_layer.audio_out", ".bias", f32t, s);
        return m;
    }

    pub fn deinit(self: *Model) void {
        for ([_]mlx.mlx_array{
            self.video_patch_w, self.video_patch_b, self.audio_patch_w, self.audio_patch_b,
            self.condition_bias, self.te_in_w,      self.te_in_b,       self.te_out_w,
            self.te_out_b,      self.inv_freq,      self.final_norm,    self.video_out_w,
            self.video_out_b,   self.audio_out_w,   self.audio_out_b,   self.refiner_final_norm,
        }) |a| _ = mlx.mlx_array_free(a);
        self.condition_proj.deinit();
        for (self.refiner) |*b| b.deinit();
        self.allocator.free(self.refiner);
        for (self.blocks) |*b| b.deinit();
        self.allocator.free(self.blocks);
        self.final_adaln.deinit();
    }

    /// Sinusoidal timestep embedding, fp32 throughout, COS BEFORE SIN.
    /// The concat order is not cosmetic: swapping the halves silently shifts
    /// every modulation the model produces.
    fn timeEmbed(self: *const Model, t_vals: []const f64, s: S) !mlx.mlx_array {
        const half = self.cfg.timestep_input_dim / 2;
        const m = t_vals.len;
        const buf = try self.allocator.alloc(f32, m * @as(usize, half) * 2);
        defer self.allocator.free(buf);
        const log10k = @log(10000.0);
        for (t_vals, 0..) |t, i| {
            for (0..half) |j| {
                const freq = @exp(-log10k * @as(f64, @floatFromInt(j)) / @as(f64, @floatFromInt(half)));
                const arg = t * freq;
                buf[i * half * 2 + j] = @floatCast(@cos(arg));
                buf[i * half * 2 + half + j] = @floatCast(@sin(arg));
            }
        }
        const shape = [_]c_int{ @intCast(m), @intCast(half * 2) };
        const emb = mlx.mlx_array_new_data(buf.ptr, &shape, 2, mlx.mlx_dtype.float32);
        defer _ = mlx.mlx_array_free(emb);
        const h1 = try denseLinear(emb, self.te_in_w, self.te_in_b, s);
        defer _ = mlx.mlx_array_free(h1);
        const a1 = try siluA(h1, s);
        defer _ = mlx.mlx_array_free(a1);
        return denseLinear(a1, self.te_out_w, self.te_out_b, s);
    }

    /// Qwen states [L, text_dim] -> refined [L, hidden].
    pub fn refineText(self: *const Model, text_states: mlx.mlx_array, s: S) !mlx.mlx_array {
        const hidden: usize = @intCast(mlx.getShape(text_states)[1]);
        if (hidden == self.cfg.hidden_size) return contig(text_states, s);
        var h = try self.condition_proj.forward(text_states, self.condition_bias, s);
        errdefer _ = mlx.mlx_array_free(h);
        for (self.refiner) |*b| {
            const n1 = try rmsNormLast(h, b.norm1, self.cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n1);
            const at = try attnForward(&b.attn, n1, self.cfg, null, s);
            defer _ = mlx.mlx_array_free(at);
            const h2 = try addA(h, at, s);
            _ = mlx.mlx_array_free(h);
            h = h2;
            const n2 = try rmsNormLast(h, b.norm2, self.cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n2);
            const mo = try mlpForward(&b.mlp, n2, s);
            defer _ = mlx.mlx_array_free(mo);
            const h3 = try addA(h, mo, s);
            _ = mlx.mlx_array_free(h);
            h = h3;
        }
        const out = try rmsNormLast(h, self.refiner_final_norm, self.cfg.final_norm_eps, s);
        _ = mlx.mlx_array_free(h);
        return out;
    }

    pub const Output = struct {
        /// Velocity for the video stream, [n_video_rows, videoPatchDim].
        video: mlx.mlx_array,
        /// Velocity for the audio stream, [n_audio_rows, audio_latents_dim],
        /// ALREADY scaled by d(sigma_a)/d(sigma_v).
        audio: mlx.mlx_array,

        pub fn deinit(self: *Output) void {
            _ = mlx.mlx_array_free(self.video);
            _ = mlx.mlx_array_free(self.audio);
        }
    };

    /// One denoising forward over the packed sequence.
    ///
    /// `video_rows` covers EVERY video-stream row in packed order (condition
    /// rows included), likewise `audio_rows`; the caller composes them from the
    /// noisy latents and the clean conditions using `layout.img_update`.
    pub fn forward(
        self: *const Model,
        layout: *const PackedLayout,
        plan: *const TimestepPlan,
        text_states: mlx.mlx_array, // [text_len, hidden] (already refined)
        video_rows: mlx.mlx_array, // [n_video_rows, videoPatchDim] f32
        audio_rows: mlx.mlx_array, // [n_audio_rows, audio_latents_dim] f32
        rope: RopeTables,
        sigma_v: f64,
        shift_v: f64,
        shift_a: f64,
        s: S,
    ) !Output {
        const a = self.allocator;
        const cfg = self.cfg;

        // Embed the two latent streams through their fp32 patch projections.
        const ve32 = try denseLinear(video_rows, self.video_patch_w, self.video_patch_b, s);
        defer _ = mlx.mlx_array_free(ve32);
        const video_embed = try astype(ve32, self.dtype, s);
        defer _ = mlx.mlx_array_free(video_embed);
        const ae32 = try denseLinear(audio_rows, self.audio_patch_w, self.audio_patch_b, s);
        defer _ = mlx.mlx_array_free(ae32);
        const audio_embed = try astype(ae32, self.dtype, s);
        defer _ = mlx.mlx_array_free(audio_embed);

        // Assemble the packed stream segment by segment. Segments are
        // contiguous and each draws from exactly one embedding stream.
        var pieces = try a.alloc(mlx.mlx_array, layout.segments.len);
        defer a.free(pieces);
        var voff: c_int = 0;
        var aoff: c_int = 0;
        var built: usize = 0;
        errdefer for (pieces[0..built]) |p| {
            _ = mlx.mlx_array_free(p);
        };
        for (layout.segments, 0..) |seg, i| {
            const n: c_int = @intCast(seg.end - seg.start);
            switch (seg.kind.stream()) {
                .text => pieces[i] = try contig(text_states, s),
                .video => {
                    pieces[i] = try sliceRows(video_embed, voff, voff + n, s);
                    voff += n;
                },
                .audio => {
                    pieces[i] = try sliceRows(audio_embed, aoff, aoff + n, s);
                    aoff += n;
                },
            }
            built += 1;
        }
        var h = try concat(pieces, 0, s);
        for (pieces) |p| _ = mlx.mlx_array_free(p);
        errdefer _ = mlx.mlx_array_free(h);

        const t_emb32 = try self.timeEmbed(plan.unique_t[0..plan.n_unique], s);
        defer _ = mlx.mlx_array_free(t_emb32);
        const t_emb = try astype(t_emb32, self.dtype, s);
        defer _ = mlx.mlx_array_free(t_emb);

        for (self.blocks) |*b| {
            var mods: [6]mlx.mlx_array = undefined;
            try b.adaln.forward(t_emb, cfg, true, &mods, s);
            defer for (&mods) |*p| {
                _ = mlx.mlx_array_free(p.*);
            };
            // 0..5 = shift_msa, scale_msa, gate_msa, shift_mlp, scale_mlp, gate_mlp
            const n1 = try rmsNormLast(h, b.norm1, cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n1);
            const m1 = try modScaleShift(n1, mods[0], mods[1], plan.runs, a, s);
            defer _ = mlx.mlx_array_free(m1);
            const at = try attnForward(&b.attn, m1, cfg, rope, s);
            defer _ = mlx.mlx_array_free(at);
            const h1 = try modGate(h, mods[2], at, plan.runs, a, s);
            _ = mlx.mlx_array_free(h);
            h = h1;

            const n2 = try rmsNormLast(h, b.norm2, cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n2);
            const m2 = try modScaleShift(n2, mods[3], mods[4], plan.runs, a, s);
            defer _ = mlx.mlx_array_free(m2);
            const mo = try mlpForward(&b.mlp, m2, s);
            defer _ = mlx.mlx_array_free(mo);
            const h2 = try modGate(h, mods[5], mo, plan.runs, a, s);
            _ = mlx.mlx_array_free(h);
            h = h2;
        }
        defer _ = mlx.mlx_array_free(h);

        // Final layer: 1 modality, so the mod row is just the timestep row.
        var fmods: [2]mlx.mlx_array = undefined;
        try self.final_adaln.forward(t_emb, cfg, true, &fmods, s);
        defer for (&fmods) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };
        const vseg = layout.videoSegment();
        const aseg = layout.audioSegment();
        const v_row = plan.runs[layout.segments.len - 1].mod_row / 3;
        const a_row = plan.runs[layout.segments.len - 2].mod_row / 3;

        const vout = try self.finalHead(h, fmods[0], fmods[1], vseg, v_row, self.video_out_w, self.video_out_b, s);
        errdefer _ = mlx.mlx_array_free(vout);
        const aout_raw = try self.finalHead(h, fmods[0], fmods[1], aseg, a_row, self.audio_out_w, self.audio_out_b, s);
        defer _ = mlx.mlx_array_free(aout_raw);

        // The sampler integrates a flat ODE on the VIDEO schedule. Scaling the
        // audio velocity by d(sigma_a)/d(sigma_v) makes that equal the audio
        // stream's true ODE on its own schedule. Both are negated: the model
        // predicts velocity, the sampler wants the denoise direction.
        const slope = timeShiftSlope(sigma_v, shift_v, shift_a);
        const negv = try scalarLike(-1.0, vout, s);
        defer _ = mlx.mlx_array_free(negv);
        const video = try mulA(vout, negv, s);
        _ = mlx.mlx_array_free(vout);
        errdefer _ = mlx.mlx_array_free(video);
        const nega = try scalarLike(@floatCast(-slope), aout_raw, s);
        defer _ = mlx.mlx_array_free(nega);
        const audio = try mulA(aout_raw, nega, s);
        return .{ .video = video, .audio = audio };
    }

    fn finalHead(self: *const Model, h: mlx.mlx_array, shift: mlx.mlx_array, scale: mlx.mlx_array, seg: Segment, row: u32, w: mlx.mlx_array, b: mlx.mlx_array, s: S) !mlx.mlx_array {
        const part = try sliceRows(h, @intCast(seg.start), @intCast(seg.end), s);
        defer _ = mlx.mlx_array_free(part);
        const nn = try rmsNormLast(part, self.final_norm, self.cfg.final_norm_eps, s);
        defer _ = mlx.mlx_array_free(nn);
        const sc = try sliceRows(scale, @intCast(row), @intCast(row + 1), s);
        defer _ = mlx.mlx_array_free(sc);
        const sh = try sliceRows(shift, @intCast(row), @intCast(row + 1), s);
        defer _ = mlx.mlx_array_free(sh);
        const one = try scalarLike(1.0, nn, s);
        defer _ = mlx.mlx_array_free(one);
        const sc1 = try addA(sc, one, s);
        defer _ = mlx.mlx_array_free(sc1);
        const m = try mulA(nn, sc1, s);
        defer _ = mlx.mlx_array_free(m);
        const mo = try addA(m, sh, s);
        defer _ = mlx.mlx_array_free(mo);
        // The output heads are fp32 islands; the reference casts here too.
        const f = try astype(mo, mlx.mlx_dtype.float32, s);
        defer _ = mlx.mlx_array_free(f);
        return denseLinear(f, w, b, s);
    }
};

// ── Text encoder (Qwen3-VL-32B, truncated to 50 layers) ─────────────────────
//
// H3's conditioning is the UNNORMALIZED hidden state after LM layer 50. The
// Comfy repack is truncated exactly there and ships no `model.norm`, so "tap
// layer 50" is simply "run every layer present and take the output".
//
// The presentation is NOT chat-templated: for t2va the ids are the raw prompt
// with NO special tokens and no prefix/suffix. Every position carries adaLN
// token tag 1 (text); only vision blocks would carry tag 0, and t2va has none.
//
// For text-only input Qwen3-VL's M-RoPE (mrope_section [24,20,20]) collapses to
// plain 1-D rotate-half RoPE, because all three axes share the running position.

pub const TeConfig = struct {
    hidden: c_int = 5120,
    heads: c_int = 64,
    kv_heads: c_int = 8,
    head_dim: c_int = 128,
    intermediate: c_int = 25600,
    layers: u32 = 50,
    theta: f64 = 5_000_000.0,
    eps: f32 = 1e-6,
};

const TeLayerW = struct {
    input_ln: mlx.mlx_array,
    post_ln: mlx.mlx_array,
    qw: MfLinear,
    kw: MfLinear,
    vw: MfLinear,
    ow: MfLinear,
    q_norm: mlx.mlx_array,
    k_norm: mlx.mlx_array,
    gate_w: MfLinear,
    up_w: MfLinear,
    down_w: MfLinear,

    fn deinit(self: *TeLayerW) void {
        inline for (.{ &self.qw, &self.kw, &self.vw, &self.ow, &self.gate_w, &self.up_w, &self.down_w }) |f| f.deinit();
        inline for (.{ self.input_ln, self.post_ln, self.q_norm, self.k_norm }) |f| _ = mlx.mlx_array_free(f);
    }
};

pub const TextEncoder = struct {
    allocator: std.mem.Allocator,
    cfg: TeConfig,
    dtype: mlx.mlx_dtype,
    embed_table: mlx.mlx_array,
    layers: []TeLayerW,

    pub fn load(allocator: std.mem.Allocator, w: *const Weights, cfg: TeConfig, dt: mlx.mlx_dtype, s: S) !TextEncoder {
        var self: TextEncoder = undefined;
        self.allocator = allocator;
        self.cfg = cfg;
        self.dtype = dt;
        const raw = try ownWeight(w, "model.embed_tokens.weight");
        defer _ = mlx.mlx_array_free(raw);
        self.embed_table = try astype(raw, dt, s);
        errdefer _ = mlx.mlx_array_free(self.embed_table);

        self.layers = try allocator.alloc(TeLayerW, cfg.layers);
        errdefer allocator.free(self.layers);
        const a = allocator;
        for (self.layers, 0..) |*layer, i| {
            const p = try std.fmt.allocPrint(a, "model.layers.{d}", .{i});
            defer a.free(p);
            const names = .{ "self_attn.q_proj", "self_attn.k_proj", "self_attn.v_proj", "self_attn.o_proj", "mlp.gate_proj", "mlp.up_proj", "mlp.down_proj" };
            var lin: [7]MfLinear = undefined;
            const in_dims = [7]c_int{ cfg.hidden, cfg.hidden, cfg.hidden, cfg.heads * cfg.head_dim, cfg.hidden, cfg.hidden, cfg.intermediate };
            inline for (names, 0..) |nm, j| {
                const full = try std.fmt.allocPrint(a, "{s}.{s}", .{ p, nm });
                defer a.free(full);
                lin[j] = try MfLinear.load(w, a, full, @intCast(in_dims[j]), dt, s);
            }
            // Norm weights stay f32: mlx_fast_rms_norm upcasts activations, and
            // a bf16 norm weight reintroduces the late-layer outlier divergence
            // mage_flow.zig documents.
            layer.* = .{
                .input_ln = try ownWeightAs(w, a, p, ".input_layernorm.weight", mlx.mlx_dtype.float32, s),
                .post_ln = try ownWeightAs(w, a, p, ".post_attention_layernorm.weight", mlx.mlx_dtype.float32, s),
                .qw = lin[0],
                .kw = lin[1],
                .vw = lin[2],
                .ow = lin[3],
                .q_norm = try ownWeightAs(w, a, p, ".self_attn.q_norm.weight", mlx.mlx_dtype.float32, s),
                .k_norm = try ownWeightAs(w, a, p, ".self_attn.k_norm.weight", mlx.mlx_dtype.float32, s),
                .gate_w = lin[4],
                .up_w = lin[5],
                .down_w = lin[6],
            };
        }
        return self;
    }

    pub fn deinit(self: *TextEncoder) void {
        _ = mlx.mlx_array_free(self.embed_table);
        for (self.layers) |*l| l.deinit();
        self.allocator.free(self.layers);
    }

    /// Raw prompt ids (NO special tokens) -> [L, hidden] layer-50 hidden state.
    /// Deliberately NOT final-normed: the checkpoint ships no `model.norm` and
    /// the reference sets `layer_norm_hidden_state=False`.
    pub fn encode(self: *const TextEncoder, ids: []const i32, s: S) !mlx.mlx_array {
        const seq: c_int = @intCast(ids.len);
        const cfg = self.cfg;

        const id_shape = [_]c_int{seq};
        const id_arr = mlx.mlx_array_new_data(ids.ptr, &id_shape, 1, mlx.mlx_dtype.int32);
        defer _ = mlx.mlx_array_free(id_arr);
        var emb = mlx.mlx_array_new();
        try mlx.check(mlx.mlx_take_axis(&emb, self.embed_table, id_arr, 0, s));
        var x = try reshape(emb, &[_]c_int{ 1, seq, cfg.hidden }, s);
        _ = mlx.mlx_array_free(emb);
        errdefer _ = mlx.mlx_array_free(x);

        var rope = try self.buildRope(seq, s);
        defer rope.deinit();
        const mask = try causalMask(seq, self.dtype, s);
        defer _ = mlx.mlx_array_free(mask);

        for (self.layers) |*layer| {
            const nx = try self.layerForward(layer, x, mask, rope, seq, s);
            _ = mlx.mlx_array_free(x);
            x = nx;
        }
        const out = try reshape(x, &[_]c_int{ seq, cfg.hidden }, s);
        _ = mlx.mlx_array_free(x);
        return out;
    }

    fn buildRope(self: *const TextEncoder, seq: c_int, s: S) !RopeTables {
        const hd: usize = @intCast(self.cfg.head_dim);
        const half = hd / 2;
        const n: usize = @intCast(seq);
        const buf = try self.allocator.alloc(f32, n * half * 2);
        defer self.allocator.free(buf);
        for (0..n) |i| {
            for (0..half) |j| {
                const inv = 1.0 / std.math.pow(f64, self.cfg.theta, @as(f64, @floatFromInt(2 * j)) / @as(f64, @floatFromInt(hd)));
                const ang = @as(f64, @floatFromInt(i)) * inv;
                buf[i * half * 2 + j] = @floatCast(@cos(ang));
                buf[i * half * 2 + half + j] = @floatCast(@sin(ang));
            }
        }
        const shape = [_]c_int{ n_c(n), @intCast(half * 2) };
        const arr = mlx.mlx_array_new_data(buf.ptr, &shape, 2, mlx.mlx_dtype.float32);
        defer _ = mlx.mlx_array_free(arr);
        var parts: [2]mlx.mlx_array = undefined;
        try splitEqual(arr, 2, 1, &parts, s);
        defer for (&parts) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };
        // [1, 1, seq, half] to broadcast against [1, H, seq, head_dim]
        const bshape = [_]c_int{ 1, 1, seq, @intCast(half) };
        const c0 = try reshape(parts[0], &bshape, s);
        defer _ = mlx.mlx_array_free(c0);
        const s0 = try reshape(parts[1], &bshape, s);
        defer _ = mlx.mlx_array_free(s0);
        var r: RopeTables = .{
            .cos = try astype(c0, self.dtype, s),
            .sin = try astype(s0, self.dtype, s),
        };
        errdefer r.deinit();
        return r;
    }

    fn layerForward(self: *const TextEncoder, layer: *const TeLayerW, x: mlx.mlx_array, mask: mlx.mlx_array, rope: RopeTables, seq: c_int, s: S) !mlx.mlx_array {
        const cfg = self.cfg;
        const xn = try rmsNormLast(x, layer.input_ln, cfg.eps, s);
        defer _ = mlx.mlx_array_free(xn);

        var qkv: [3]mlx.mlx_array = undefined;
        const heads = [3]c_int{ cfg.heads, cfg.kv_heads, cfg.kv_heads };
        inline for (.{ &layer.qw, &layer.kw, &layer.vw }, 0..) |lw, i| {
            const p = try lw.forward(xn, null, s);
            defer _ = mlx.mlx_array_free(p);
            const r4 = try reshape(p, &[_]c_int{ 1, seq, heads[i], cfg.head_dim }, s);
            if (i == 2) {
                defer _ = mlx.mlx_array_free(r4);
                const t = try transpose(r4, &[_]c_int{ 0, 2, 1, 3 }, s);
                defer _ = mlx.mlx_array_free(t);
                qkv[i] = try contig(t, s);
            } else {
                defer _ = mlx.mlx_array_free(r4);
                const nw = if (i == 0) layer.q_norm else layer.k_norm;
                const nn = try rmsNormLast(r4, nw, cfg.eps, s);
                defer _ = mlx.mlx_array_free(nn);
                const t = try transpose(nn, &[_]c_int{ 0, 2, 1, 3 }, s);
                defer _ = mlx.mlx_array_free(t);
                const tc = try contig(t, s);
                defer _ = mlx.mlx_array_free(tc);
                qkv[i] = try ropeHalf(tc, rope, cfg.head_dim, s);
            }
        }
        defer for (&qkv) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };

        const scale: f32 = 1.0 / @sqrt(@as(f32, @floatFromInt(cfg.head_dim)));
        var attn = mlx.mlx_array_new();
        defer _ = mlx.mlx_array_free(attn);
        const null_sink = mlx.mlx_array{ .ctx = null };
        try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&attn, qkv[0], qkv[1], qkv[2], scale, "array", mask, null_sink, s));
        const at = try transpose(attn, &[_]c_int{ 0, 2, 1, 3 }, s);
        defer _ = mlx.mlx_array_free(at);
        const af = try reshape(at, &[_]c_int{ 1, seq, cfg.heads * cfg.head_dim }, s);
        defer _ = mlx.mlx_array_free(af);
        const o = try layer.ow.forward(af, null, s);
        defer _ = mlx.mlx_array_free(o);
        const h1 = try addA(x, o, s);
        defer _ = mlx.mlx_array_free(h1);

        const hn = try rmsNormLast(h1, layer.post_ln, cfg.eps, s);
        defer _ = mlx.mlx_array_free(hn);
        const g = try layer.gate_w.forward(hn, null, s);
        defer _ = mlx.mlx_array_free(g);
        const sg = try siluA(g, s);
        defer _ = mlx.mlx_array_free(sg);
        const u = try layer.up_w.forward(hn, null, s);
        defer _ = mlx.mlx_array_free(u);
        const gu = try mulA(sg, u, s);
        defer _ = mlx.mlx_array_free(gu);
        const d = try layer.down_w.forward(gu, null, s);
        defer _ = mlx.mlx_array_free(d);
        return addA(h1, d, s);
    }
};

inline fn n_c(v: usize) c_int {
    return @intCast(v);
}

/// Standard rotate-half RoPE on [1, H, seq, head_dim].
fn ropeHalf(x: mlx.mlx_array, rope: RopeTables, head_dim: c_int, s: S) !mlx.mlx_array {
    const half = @divExact(head_dim, 2);
    const x1 = try sliceLast4(x, 0, half, s);
    defer _ = mlx.mlx_array_free(x1);
    const x2 = try sliceLast4(x, half, head_dim, s);
    defer _ = mlx.mlx_array_free(x2);
    const a1 = try mulA(x1, rope.cos, s);
    defer _ = mlx.mlx_array_free(a1);
    const a2 = try mulA(x2, rope.sin, s);
    defer _ = mlx.mlx_array_free(a2);
    var o1 = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o1);
    try mlx.check(mlx.mlx_subtract(&o1, a1, a2, s));
    const b1 = try mulA(x2, rope.cos, s);
    defer _ = mlx.mlx_array_free(b1);
    const b2 = try mulA(x1, rope.sin, s);
    defer _ = mlx.mlx_array_free(b2);
    const o2 = try addA(b1, b2, s);
    defer _ = mlx.mlx_array_free(o2);
    return concat(&[_]mlx.mlx_array{ o1, o2 }, 3, s);
}

/// Additive causal mask [1, 1, seq, seq]. Built with `where`, never by
/// multiplying an indicator by -inf: 0 * -inf is NaN, and a NaN mask passes a
/// parity loop that compares before it checks finiteness.
fn causalMask(seq: c_int, dt: mlx.mlx_dtype, s: S) !mlx.mlx_array {
    var rows = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(rows);
    try mlx.check(mlx.mlx_arange(&rows, 0, @floatFromInt(seq), 1, mlx.mlx_dtype.int32, s));
    const r = try reshape(rows, &[_]c_int{ seq, 1 }, s);
    defer _ = mlx.mlx_array_free(r);
    const c = try reshape(rows, &[_]c_int{ 1, seq }, s);
    defer _ = mlx.mlx_array_free(c);
    var keep = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(keep);
    try mlx.check(mlx.mlx_greater_equal(&keep, r, c, s));

    const zero = mlx.mlx_array_new_float(0);
    defer _ = mlx.mlx_array_free(zero);
    const neg = mlx.mlx_array_new_float(-std.math.inf(f32));
    defer _ = mlx.mlx_array_free(neg);
    var m = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(m);
    try mlx.check(mlx.mlx_where(&m, keep, zero, neg, s));
    const m4 = try reshape(m, &[_]c_int{ 1, 1, seq, seq }, s);
    defer _ = mlx.mlx_array_free(m4);
    return astype(m4, dt, s);
}

// ── Sampler ─────────────────────────────────────────────────────────────────

/// Flow-match sigma schedule on the VIDEO shift.
///
/// `sigmas[i] = shift*b / (1 + (shift-1)*b)` for `b = 1 - i/steps`, i.e. the
/// base grid pushed through the same time shift the DiT inverts internally.
/// Caller owns the returned slice (length steps+1, ending at 0).
pub fn sigmaSchedule(allocator: std.mem.Allocator, steps: u32, shift: f64) ![]f64 {
    const out = try allocator.alloc(f64, steps + 1);
    errdefer allocator.free(out);
    for (0..steps + 1) |i| {
        const base = 1.0 - @as(f64, @floatFromInt(i)) / @as(f64, @floatFromInt(steps));
        out[i] = timeShiftSigma(base, 1.0, shift);
    }
    return out;
}

pub const GenRequest = struct {
    prompt: []const u8,
    width: u32 = 256,
    height: u32 = 256,
    /// Requested source frames; snapped UP to the 17k+5 ladder.
    frames: u32 = 56,
    steps: u32 = 30,
    seed: u64 = 0,
    shift_video: f64 = SIGMA_SHIFT_VIDEO,
    shift_audio: f64 = SIGMA_SHIFT_AUDIO,
};

pub const GenPaths = struct {
    /// Directory holding tokenizer.json.
    tokenizer_dir: []const u8,
    text_encoder: []const u8,
    dit: []const u8,
    vae: []const u8,
    /// Audio VAE. Optional: absent means the clip is silent rather than
    /// failing, since the video stream is complete without it.
    audio_vae: ?[]const u8 = null,
};

pub const GenResult = struct {
    /// [1, 3, frames, H, W] in [-1, 1].
    pixels: mlx.mlx_array,
    /// Final audio latent [1, 32, 2, audio_t], still in latent space.
    audio_latent: mlx.mlx_array,
    /// Decoded stereo waveform [2, L] at 32 kHz, when an audio VAE was given.
    audio: ?mlx.mlx_array = null,
    frame_count: u32,
    width: u32,
    height: u32,

    pub fn deinit(self: *GenResult) void {
        _ = mlx.mlx_array_free(self.pixels);
        _ = mlx.mlx_array_free(self.audio_latent);
        if (self.audio) |a| _ = mlx.mlx_array_free(a);
    }
};

fn randomNormal(shape: []const c_int, seed: u64, dt: mlx.mlx_dtype, s: S) !mlx.mlx_array {
    var key = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(key);
    try mlx.check(mlx.mlx_random_key(&key, seed));
    var o = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o);
    try mlx.check(mlx.mlx_random_normal(&o, shape.ptr, shape.len, mlx.mlx_dtype.float32, 0.0, 1.0, key, s));
    return astype(o, dt, s);
}

/// Text-to-audio-video, with STAGED residency: the 50-layer text encoder
/// (~48 GB bf16) and the DiT (~62 GB bf16) cannot both be resident on a 128 GB
/// machine, so the encoder is loaded, run, and freed before the DiT loads.
pub fn generate(
    allocator: std.mem.Allocator,
    io: std.Io,
    paths: GenPaths,
    req: GenRequest,
    progress: ?gen_sse.Progress,
    s: S,
) !GenResult {
    const vae_mod = @import("minimax_h3_vae.zig");
    const dt = mlx.mlx_dtype.bfloat16;

    const shape = temporalShape(req.frames);
    const lat_h = req.height / vae_mod.VAE_RATIO;
    const lat_w = req.width / vae_mod.VAE_RATIO;
    log.info("[minimax-h3] {d}x{d} {d} frames ({d} latent, {d} audio), {d} steps\n", .{
        req.width, req.height, shape.frame_count, shape.latent_t, shape.audio_t, req.steps,
    });

    // ── 1. tokenize (raw ids, NO special tokens and no chat template) ──
    const tok_mod = @import("tokenizer.zig");
    var tok = try tok_mod.loadTokenizerAny(io, allocator, paths.tokenizer_dir);
    defer tok.deinit();
    const ids_u32 = try tok.encode(allocator, req.prompt);
    defer allocator.free(ids_u32);
    const ids = try allocator.alloc(i32, ids_u32.len);
    defer allocator.free(ids);
    for (ids_u32, 0..) |v, i| ids[i] = @intCast(v);
    log.info("[minimax-h3] prompt -> {d} tokens\n", .{ids.len});

    if (progress) |p| p.emit("Encoding prompt", 0, req.steps);

    // ── 2. text encoder, then FREE it before the DiT loads ──
    const text_hidden: mlx.mlx_array = blk: {
        var tw = try model_mod.loadWeightsSingleFile(allocator, paths.text_encoder);
        defer tw.deinit();
        var te = try TextEncoder.load(allocator, &tw, .{}, dt, s);
        defer te.deinit();
        const h = try te.encode(ids, s);
        try mlx.check(mlx.mlx_array_eval(h));
        break :blk h;
    };
    defer _ = mlx.mlx_array_free(text_hidden);
    _ = mlx.mlx_clear_cache();
    log.info("[minimax-h3] text encoded, encoder released\n", .{});

    // ── 3. DiT sampling ──
    var layout = try PackedLayout.init(allocator, @intCast(ids.len), shape.latent_t, lat_h, lat_w, shape.audio_t, &.{}, shape.frame_count);
    defer layout.deinit();

    const n_video_rows: c_int = @intCast(shape.latent_t * (lat_h / PATCH_H) * (lat_w / PATCH_W));
    const n_audio_rows: c_int = @intCast(shape.audio_t * 2);

    const vpatch: c_int = @intCast((Config{}).videoPatchDim());
    var video_x = try randomNormal(&[_]c_int{ n_video_rows, vpatch }, req.seed, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(video_x);
    var audio_x = try randomNormal(&[_]c_int{ n_audio_rows, 32 }, req.seed +% 1, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(audio_x);

    const sigmas = try sigmaSchedule(allocator, req.steps, req.shift_video);
    defer allocator.free(sigmas);

    {
        var dw = try model_mod.loadWeightsSingleFile(allocator, paths.dit);
        defer dw.deinit();
        var model = try Model.load(allocator, &dw, .{}, dt, s);
        defer model.deinit();

        const refined = try model.refineText(text_hidden, s);
        defer _ = mlx.mlx_array_free(refined);

        var rope = try buildRope(allocator, &layout, model.inv_freq, dt, s);
        defer rope.deinit();

        for (0..req.steps) |i| {
            const sigma = sigmas[i];
            const dsigma = sigmas[i + 1] - sigmas[i];
            var plan = try buildTimestepPlan(allocator, &layout, sigma, req.shift_video, req.shift_audio, .{});
            defer plan.deinit();

            var out = try model.forward(&layout, &plan, refined, video_x, audio_x, rope, sigma, req.shift_video, req.shift_audio, s);
            defer out.deinit();

            // Euler on the flat ODE: x += model_output * dsigma. The audio
            // velocity already carries d(sigma_a)/d(sigma_v), so both streams
            // integrate against the SAME video-schedule step.
            const dv = try scalarLike(@floatCast(dsigma), out.video, s);
            defer _ = mlx.mlx_array_free(dv);
            const stepv = try mulA(out.video, dv, s);
            defer _ = mlx.mlx_array_free(stepv);
            const nv = try addA(video_x, stepv, s);
            _ = mlx.mlx_array_free(video_x);
            video_x = nv;

            const da = try scalarLike(@floatCast(dsigma), out.audio, s);
            defer _ = mlx.mlx_array_free(da);
            const stepa = try mulA(out.audio, da, s);
            defer _ = mlx.mlx_array_free(stepa);
            const na = try addA(audio_x, stepa, s);
            _ = mlx.mlx_array_free(audio_x);
            audio_x = na;

            try mlx.check(mlx.mlx_array_eval(video_x));
            try mlx.check(mlx.mlx_array_eval(audio_x));
            if (progress) |p| {
                // Poll BEFORE emitting: a vanished client should stop the GPU,
                // not have one more step charged to it first.
                if (p.cancelled()) return error.Cancelled;
                p.emit("Generating", @intCast(i + 1), req.steps);
            }
            // Every denoise loop owes a periodic cache clear: MLX's pool is
            // unbounded and these shapes repeat, so without it the process
            // footprint ratchets across steps.
            _ = mlx.mlx_clear_cache();
            log.info("[minimax-h3] step {d}/{d} sigma {d:.4}\n", .{ i + 1, req.steps, sigma });
        }
    }
    _ = mlx.mlx_clear_cache();
    log.info("[minimax-h3] sampling done, DiT released\n", .{});

    // ── 4. VAE decode ──
    // Unpatchify the video rows back to a latent volume: rows are
    // (t, h/2, w/2) major with C*2*2 per row.
    const lh2: c_int = @intCast(lat_h / PATCH_H);
    const lw2: c_int = @intCast(lat_w / PATCH_W);
    const c24: c_int = 24;
    const v6 = try reshape(video_x, &[_]c_int{ @intCast(shape.latent_t), lh2, lw2, c24, @intCast(PATCH_H), @intCast(PATCH_W) }, s);
    defer _ = mlx.mlx_array_free(v6);
    // (t,h,w,c,ph,pw) -> (c, t, h, ph, w, pw)
    const vp = try transpose(v6, &[_]c_int{ 3, 0, 1, 4, 2, 5 }, s);
    defer _ = mlx.mlx_array_free(vp);
    const vpc = try contig(vp, s);
    defer _ = mlx.mlx_array_free(vpc);
    const zlat = try reshape(vpc, &[_]c_int{ 1, c24, @intCast(shape.latent_t), @intCast(lat_h), @intCast(lat_w) }, s);
    defer _ = mlx.mlx_array_free(zlat);

    if (progress) |p| p.emit("Decoding video", req.steps, req.steps);
    var vw = try model_mod.loadWeightsSingleFile(allocator, paths.vae);
    defer vw.deinit();
    var dec = try vae_mod.Decoder.load(allocator, &vw, .{}, dt, s);
    defer dec.deinit();
    const pixels = try vae_mod.decode(&dec, zlat, allocator, s);
    errdefer _ = mlx.mlx_array_free(pixels);
    try mlx.check(mlx.mlx_array_eval(pixels));
    _ = mlx.mlx_clear_cache();

    // Audio rows [ch*T, 32] -> [1, 32, 2, T]
    const at: c_int = @intCast(shape.audio_t);
    const a3 = try reshape(audio_x, &[_]c_int{ 2, at, 32 }, s);
    defer _ = mlx.mlx_array_free(a3);
    const ap = try transpose(a3, &[_]c_int{ 2, 0, 1 }, s);
    defer _ = mlx.mlx_array_free(ap);
    const apc = try contig(ap, s);
    defer _ = mlx.mlx_array_free(apc);
    const audio_latent = try reshape(apc, &[_]c_int{ 1, 32, 2, at }, s);
    errdefer _ = mlx.mlx_array_free(audio_latent);

    // ── 5. audio VAE (optional) ──
    var audio_wave: ?mlx.mlx_array = null;
    if (paths.audio_vae) |apath| {
        if (progress) |p| p.emit("Decoding audio", req.steps, req.steps);
        const audio_mod = @import("minimax_h3_audio.zig");
        var aw = try model_mod.loadWeightsSingleFile(allocator, apath);
        defer aw.deinit();
        const wave = try audio_mod.decode(allocator, &aw, audio_latent, dt, s);
        try mlx.check(mlx.mlx_array_eval(wave));
        audio_wave = wave;
        _ = mlx.mlx_clear_cache();
        log.info("[minimax-h3] audio decoded: {d} samples/ch at {d} Hz\n", .{ mlx.getShape(wave)[1], audio_mod.SAMPLE_RATE });
    }

    const pshape = mlx.getShape(pixels);
    return .{
        .pixels = pixels,
        .audio_latent = audio_latent,
        .audio = audio_wave,
        .frame_count = @intCast(pshape[2]),
        .height = @intCast(pshape[3]),
        .width = @intCast(pshape[4]),
    };
}

// ── Output conversion ───────────────────────────────────────────────────────

/// [1,3,F,H,W] in [-1,1] -> tightly packed [F,H,W,3] u8. Caller owns.
pub fn pixelsToRgb8(allocator: std.mem.Allocator, res: *const GenResult, s: S) ![]u8 {
    const p = try transpose(res.pixels, &[_]c_int{ 0, 2, 3, 4, 1 }, s);
    defer _ = mlx.mlx_array_free(p);
    const pc = try contig(p, s);
    defer _ = mlx.mlx_array_free(pc);
    const one = try scalarLike(1.0, pc, s);
    defer _ = mlx.mlx_array_free(one);
    const shifted = try addA(pc, one, s);
    defer _ = mlx.mlx_array_free(shifted);
    const k = try scalarLike(127.5, shifted, s);
    defer _ = mlx.mlx_array_free(k);
    const scaled = try mulA(shifted, k, s);
    defer _ = mlx.mlx_array_free(scaled);
    const u8a = try astype(scaled, mlx.mlx_dtype.uint8, s);
    defer _ = mlx.mlx_array_free(u8a);
    try mlx.check(mlx.mlx_array_eval(u8a));
    const n: usize = @intCast(mlx.mlx_array_size(u8a));
    const raw = mlx.mlx_array_data_uint8(u8a) orelse return error.NoPixelData;
    return allocator.dupe(u8, raw[0..n]);
}

/// Stereo [2, L] f32 -> interleaved little-endian 16-bit PCM. Caller owns.
pub fn audioToPcm16(allocator: std.mem.Allocator, wave: mlx.mlx_array, s: S) ![]u8 {
    const t = try transpose(wave, &[_]c_int{ 1, 0 }, s);
    defer _ = mlx.mlx_array_free(t);
    const tc = try contig(t, s);
    defer _ = mlx.mlx_array_free(tc);
    const f = try astype(tc, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(f);
    try mlx.check(mlx.mlx_array_eval(f));
    const n: usize = @intCast(mlx.mlx_array_size(f));
    const raw = mlx.mlx_array_data_float32(f) orelse return error.NoAudioData;
    const out = try allocator.alloc(u8, n * 2);
    errdefer allocator.free(out);
    for (0..n) |i| {
        // The vocoder already clamps to [-1,1]; clamp again so a future change
        // upstream cannot wrap a sample to the opposite rail.
        const v = std.math.clamp(raw[i], -1.0, 1.0);
        const q: i16 = @intFromFloat(v * 32767.0);
        std.mem.writeInt(i16, out[i * 2 ..][0..2], q, .little);
    }
    return out;
}

