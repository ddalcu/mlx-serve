// Live end-to-end generation. Env-gated like the other weight-dependent
// oracles in this repo (DSV4_TEST_MODEL, MAGEFLOW_*), because it needs ~115 GB
// of checkpoints staged on disk and takes minutes.
//
//   MINIMAX_H3_DIR=~/claude-tmp/h3-build \
//   MINIMAX_H3_OUT=~/claude-tmp/h3-build/out \
//   MINIMAX_H3_STEPS=30 MINIMAX_H3_FRAMES=56 MINIMAX_H3_SIZE=256 \
//   zig build test -Doptimize=ReleaseFast -Dtest-filter="minimax h3 live"
//
// Writes a PNG per frame. The mp4 mux lives in the Swift app (AVAssetWriter),
// matching how the LTX path already delivers video.
test "minimax h3 live: generates a clip" {
    const dir = envStr("MINIMAX_H3_DIR") orelse return error.SkipZigTest;
    log.enableStderr(); // the phase/step lines are this harness's output
    const a = testing.allocator;
    const io = std.Io.Threaded.global_single_threaded.io();
    const s = mlx.gpuStream();

    const size = envU32("MINIMAX_H3_SIZE", 256);
    const frames = envU32("MINIMAX_H3_FRAMES", 56);
    const steps = envU32("MINIMAX_H3_STEPS", 30);
    const out_dir = envStr("MINIMAX_H3_OUT") orelse "/tmp/h3out";

    // Two layouts are accepted so the SAME test covers both: the raw staging
    // tree of upstream bf16 files, and a converted model dir from
    // tests/convert_minimax_h3_weights.py (which is also what the app will
    // ship). Both load through MfLinear's one geometry solve — running the
    // quantized dir here is what proves that.
    const converted = envStr("MINIMAX_H3_MODEL");
    const te = if (converted) |m|
        try std.fmt.allocPrint(a, "{s}/text_encoder.safetensors", .{m})
    else
        try std.fmt.allocPrint(a, "{s}/src/text_encoders/qwen3vl_32b_minimax_h3_bf16.safetensors", .{dir});
    defer a.free(te);
    const dit = if (converted) |m|
        try std.fmt.allocPrint(a, "{s}/transformer.safetensors", .{m})
    else
        try std.fmt.allocPrint(a, "{s}/src/diffusion_models/minimax_h3_fl2va_bf16.safetensors", .{dir});
    defer a.free(dit);
    const vae = if (converted) |m|
        try std.fmt.allocPrint(a, "{s}/video_vae.safetensors", .{m})
    else
        try std.fmt.allocPrint(a, "{s}/src/vae/minimax_h3_video_vae_fp16.safetensors", .{dir});
    defer a.free(vae);
    const avae = if (converted) |m|
        try std.fmt.allocPrint(a, "{s}/audio_vae.safetensors", .{m})
    else
        try std.fmt.allocPrint(a, "{s}/src/vae/minimax_h3_audio_vae_fp32.safetensors", .{dir});
    defer a.free(avae);
    const tokdir = if (converted) |m|
        try std.fmt.allocPrint(a, "{s}", .{m})
    else
        try std.fmt.allocPrint(a, "{s}/src_orig/FL2VA/processor", .{dir});
    defer a.free(tokdir);

    const prompt = envStr("MINIMAX_H3_PROMPT") orelse
        "A calico cat sits on a sunlit windowsill, slowly blinking as it watches rain streak down the glass. " ++
        "The camera holds steady in a close medium shot. Warm afternoon light rims the cat's fur against the cool grey outside. " ++
        "overall_soundscape: steady rainfall against glass with a soft room tone and the cat's quiet purring.";

    var res = try generate(a, io, .{
        .tokenizer_dir = tokdir,
        .text_encoder = te,
        .dit = dit,
        .vae = vae,
        .audio_vae = avae,
    }, .{
        .prompt = prompt,
        .width = envU32("MINIMAX_H3_WIDTH", size),
        .height = size,
        .frames = frames,
        .steps = steps,
    }, null, s);
    defer res.deinit();

    // The pipeline can produce a plausible-looking tensor full of NaN; a
    // finiteness check has to come BEFORE anything that inspects values.
    const finite = try allFinite(res.pixels, s);
    try testing.expect(finite);
    try testing.expectEqual(alignFrameCount(@max(5, frames)), res.frame_count);
    try testing.expectEqual(envU32("MINIMAX_H3_WIDTH", size), res.width);
    try testing.expectEqual(size, res.height);

    try writeFrames(a, io, &res, out_dir, s);

    // Audio must be finite AND non-silent: an all-zero waveform passes every
    // shape assertion and is exactly what a broken vocoder produces.
    const wave = res.audio orelse return error.MissingAudio;
    try testing.expect(try allFinite(wave, s));
    const peak = try absMax(wave, s);
    std.debug.print("[minimax-h3] audio peak {d:.4}\n", .{peak});
    try testing.expect(peak > 0.001);
    try testing.expect(peak <= 1.0); // the vocoder clamps
    try writeWav(a, io, wave, out_dir, s);

    std.debug.print("[minimax-h3] wrote {d} frames {d}x{d} to {s}\n", .{ res.frame_count, res.width, res.height, out_dir });
}

/// libc getenv, matching generate.zig's allocator-free env idiom.
fn envStr(name: [:0]const u8) ?[]const u8 {
    const raw = std.c.getenv(name.ptr) orelse return null;
    const slice = std.mem.sliceTo(raw, 0);
    return if (slice.len == 0) null else slice;
}

fn envU32(name: [:0]const u8, dflt: u32) u32 {
    const v = envStr(name) orelse return dflt;
    return std.fmt.parseInt(u32, v, 10) catch dflt;
}

fn allFinite(x: mlx.mlx_array, s: S) !bool {
    var isf = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(isf);
    try mlx.check(mlx.mlx_isfinite(&isf, x, s));
    var allv = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(allv);
    try mlx.check(mlx.mlx_all(&allv, isf, false, s));
    try mlx.check(mlx.mlx_array_eval(allv));
    var b: bool = false;
    try mlx.check(mlx.mlx_array_item_bool(&b, allv));
    return b;
}

/// [-1,1] pixels -> 8-bit RGB frames on disk (raw + PNG).
fn writeFrames(a: std.mem.Allocator, io: std.Io, res: *const GenResult, out_dir: []const u8, s: S) !void {
    const png = @import("png.zig");
    // [1,3,F,H,W] -> [F,H,W,3] u8
    const p = try transpose(res.pixels, &[_]c_int{ 0, 2, 3, 4, 1 }, s);
    defer _ = mlx.mlx_array_free(p);
    const pc = try contig(p, s);
    defer _ = mlx.mlx_array_free(pc);
    const half = try scalarLike(0.5, pc, s);
    defer _ = mlx.mlx_array_free(half);
    const shifted = try addA(pc, try oneLike(pc, s), s);
    defer _ = mlx.mlx_array_free(shifted);
    const unit = try mulA(shifted, half, s);
    defer _ = mlx.mlx_array_free(unit);
    const c255 = try scalarLike(255.0, unit, s);
    defer _ = mlx.mlx_array_free(c255);
    const scaled = try mulA(unit, c255, s);
    defer _ = mlx.mlx_array_free(scaled);
    const u8a = try astype(scaled, mlx.mlx_dtype.uint8, s);
    defer _ = mlx.mlx_array_free(u8a);
    try mlx.check(mlx.mlx_array_eval(u8a));

    const n = res.frame_count * res.height * res.width * 3;
    const raw = mlx.mlx_array_data_uint8(u8a) orelse return error.NoPixelData;

    std.Io.Dir.cwd().createDirPath(io, out_dir) catch {};
    var d = try std.Io.Dir.cwd().openDir(io, out_dir, .{});
    defer d.close(io);

    const frame_bytes = res.height * res.width * 3;
    for (0..res.frame_count) |f| {
        const slice = raw[f * frame_bytes ..][0..frame_bytes];
        const bytes = try png.encodeRgb(a, slice, res.width, res.height);
        defer a.free(bytes);
        const name = try std.fmt.allocPrint(a, "frame_{d:0>4}.png", .{f});
        defer a.free(name);
        var fh = try d.createFile(io, name, .{});
        defer fh.close(io);
        var wbuf: [4096]u8 = undefined;
        var w = fh.writer(io, &wbuf);
        try w.interface.writeAll(bytes);
        try w.interface.flush();
    }
    _ = n;
}

fn oneLike(like: mlx.mlx_array, s: S) !mlx.mlx_array {
    return scalarLike(1.0, like, s);
}

fn meanAbs(x: mlx.mlx_array, s: S) !f32 {
    var ab = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(ab);
    try mlx.check(mlx.mlx_abs(&ab, x, s));
    var mv = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(mv);
    try mlx.check(mlx.mlx_mean(&mv, ab, false, s));
    try mlx.check(mlx.mlx_array_eval(mv));
    var v: f32 = 0;
    try mlx.check(mlx.mlx_array_item_float32(&v, mv));
    return v;
}

fn absMax(x: mlx.mlx_array, s: S) !f32 {
