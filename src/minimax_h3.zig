    expand: u32,
    /// 3 for a DiT block (video/text/audio), 1 for the final layer.
    modalities: u32,

    fn load(w: *const Weights, a: std.mem.Allocator, prefix: []const u8, cfg: Config, expand: u32, modalities: u32, dt: mlx.mlx_dtype, s: S) !AdalnW {
        const p = try std.fmt.allocPrint(a, "{s}.linear", .{prefix});
        defer a.free(p);
        var r: AdalnW = .{
            .linear = try MfLinear.load(w, a, p, cfg.time_embed_dim, dt, s),
            .bias = try ownWeightAs(w, a, prefix, ".linear.bias", dt, s),
            .expand = expand,
            .modalities = modalities,
        };
        errdefer r.deinit();
        return r;
    }
    fn deinit(self: *AdalnW) void {
        self.linear.deinit();
        _ = mlx.mlx_array_free(self.bias);
    }

    /// t_emb [M, time_embed_dim] -> `expand` arrays of [M*modalities, hidden].
    /// Row `t_row * modalities + tag` is the modulation for that timestep and
    /// stream, which is what `SegmentKind.modalityTag` indexes.
    fn forward(self: *const AdalnW, t_emb: mlx.mlx_array, cfg: Config, apply_silu: bool, out: []mlx.mlx_array, s: S) !void {
        std.debug.assert(out.len == self.expand);
        const inp = if (apply_silu) try siluA(t_emb, s) else try contig(t_emb, s);
        defer _ = mlx.mlx_array_free(inp);
        const y = try self.linear.forward(inp, self.bias, s);
        defer _ = mlx.mlx_array_free(y);
        const m: c_int = @intCast(mlx.getShape(y)[0]);
        const rows = m * @as(c_int, @intCast(self.modalities));
        const cols = @as(c_int, @intCast(self.expand * cfg.hidden_size));
        const v = try reshape(y, &[_]c_int{ rows, cols }, s);
        defer _ = mlx.mlx_array_free(v);
        try splitEqual(v, self.expand, 1, out, s);
    }
};

