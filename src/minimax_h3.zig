/// Precomputed rotary tables for one packed layout. cos/sin are [S, rot/2].
pub const RopeTables = struct {
    cos: mlx.mlx_array,
    sin: mlx.mlx_array,

    pub fn deinit(self: *RopeTables) void {
        _ = mlx.mlx_array_free(self.cos);
        _ = mlx.mlx_array_free(self.sin);
    }
};

/// Build cos/sin from the layout's [S,3] positions and the checkpoint's
/// inv_freq [16]. Angles are concat(t*inv, h*inv, w*inv) = 48 values, and the
/// split-half pairing rotates dim i against dim i+48.
pub fn buildRope(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    inv_freq: mlx.mlx_array,
    dt: mlx.mlx_dtype,
    s: S,
) !RopeTables {
    const n = layout.seq_len;
    const nf = mlx.getShape(inv_freq)[0]; // 16
    const half: usize = @as(usize, @intCast(nf)) * 3; // 48

    // Positions ride to the GPU as f32. The reference builds the grid in f64
    // and casts here, so this cast is the reference's, not a shortcut.
    const pos_f32 = try allocator.alloc(f32, @as(usize, n) * 3);
    defer allocator.free(pos_f32);
    for (layout.position_ids, 0..) |v, i| pos_f32[i] = @floatCast(v);

    const shape = [_]c_int{ @intCast(n), 3, 1 };
    const pos = mlx.mlx_array_new_data(pos_f32.ptr, &shape, 3, mlx.mlx_dtype.float32);
    defer _ = mlx.mlx_array_free(pos);

    const inv_shape = [_]c_int{ 1, 1, @intCast(nf) };
    const inv3 = try reshape(inv_freq, &inv_shape, s);
    defer _ = mlx.mlx_array_free(inv3);
    const inv_f32 = try astype(inv3, mlx.mlx_dtype.float32, s);
    defer _ = mlx.mlx_array_free(inv_f32);

    // [S,3,1] * [1,1,16] -> [S,3,16] -> [S,48], axis order t,h,w
    const per_axis = try mulA(pos, inv_f32, s);
    defer _ = mlx.mlx_array_free(per_axis);
    const ang = try reshape(per_axis, &[_]c_int{ @intCast(n), @intCast(half) }, s);
    defer _ = mlx.mlx_array_free(ang);

    var c = mlx.mlx_array_new();
    errdefer _ = mlx.mlx_array_free(c);
    try mlx.check(mlx.mlx_cos(&c, ang, s));
    var sn = mlx.mlx_array_new();
    errdefer _ = mlx.mlx_array_free(sn);
    try mlx.check(mlx.mlx_sin(&sn, ang, s));

    // Broadcast slot for [1, S, 1, half] against q/k [1, S, H, head_dim].
    const bshape = [_]c_int{ 1, @intCast(n), 1, @intCast(half) };
    const cb = try reshape(c, &bshape, s);
    _ = mlx.mlx_array_free(c);
    errdefer _ = mlx.mlx_array_free(cb);
    const sb = try reshape(sn, &bshape, s);
    _ = mlx.mlx_array_free(sn);
    errdefer _ = mlx.mlx_array_free(sb);

    const cd = try astype(cb, dt, s);
    _ = mlx.mlx_array_free(cb);
    errdefer _ = mlx.mlx_array_free(cd);
    const sd = try astype(sb, dt, s);
    _ = mlx.mlx_array_free(sb);
    return .{ .cos = cd, .sin = sd };
}

/// Partial split-half rotary on [1, S, H, head_dim]: dims [0,48) pair with
/// [48,96); dims [96,128) pass through UNROTATED. Getting the pass-through
/// wrong (rotating the full head) is silent — the model still runs.
pub fn applyRopePub(x: mlx.mlx_array, rope: RopeTables, half: c_int, head_dim: c_int, s: S) !mlx.mlx_array {
    const x1 = try sliceLast4(x, 0, half, s);
    defer _ = mlx.mlx_array_free(x1);
    const x2 = try sliceLast4(x, half, half * 2, s);
    defer _ = mlx.mlx_array_free(x2);

    const a1 = try mulA(x1, rope.cos, s);
    defer _ = mlx.mlx_array_free(a1);
    const a2 = try mulA(x2, rope.sin, s);
    defer _ = mlx.mlx_array_free(a2);
    var o1 = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o1);
    try mlx.check(mlx.mlx_subtract(&o1, a1, a2, s));

    const b1 = try mulA(x1, rope.sin, s);
    defer _ = mlx.mlx_array_free(b1);
    const b2 = try mulA(x2, rope.cos, s);
    defer _ = mlx.mlx_array_free(b2);
    const o2 = try addA(b1, b2, s);
    defer _ = mlx.mlx_array_free(o2);

    if (half * 2 == head_dim) return concat(&[_]mlx.mlx_array{ o1, o2 }, 3, s);
    const tail = try sliceLast4(x, half * 2, head_dim, s);
    defer _ = mlx.mlx_array_free(tail);
    return concat(&[_]mlx.mlx_array{ o1, o2, tail }, 3, s);
}

/// Sparse attention core over post-rope [1, H, S, hd] q/k/v.
///
/// Strip queries (rows [0, video_start)) keep FULL attention; video queries
/// attend to their pattern's video keys PLUS the strip, via batched SDPA with
/// the frame/stripe axis folded into the batch dim. Key order inside a
/// subset differs from the dense order — softmax is permutation-invariant
/// over keys up to fp rounding, which is inside the sanctioned class.
fn sparseAttend(q: mlx.mlx_array, k: mlx.mlx_array, v: mlx.mlx_array, spec: SparseSpec, scale: f32, s: S) !mlx.mlx_array {
    const shp = mlx.getShape(q);
    const nh = shp[1];
    const seq = shp[2];
    const hd = shp[3];
    const g: c_int = @intCast(spec.video_start);
    const t: c_int = @intCast(spec.t);
    const f: c_int = @intCast(spec.f);
    std.debug.assert(g + t * f == seq);
    const null_a = mlx.mlx_array{ .ctx = null };

    // Strip queries: full attention over every key.
    const qg = try sliceAxis4(q, 2, 0, g, s);
    defer _ = mlx.mlx_array_free(qg);
    var og = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(og);
    try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&og, qg, k, v, scale, "", null_a, null_a, s));

    // Video split + strip keys.
    const qv = try sliceAxis4(q, 2, g, seq, s);
    defer _ = mlx.mlx_array_free(qv);
    const kv = try sliceAxis4(k, 2, g, seq, s);
    defer _ = mlx.mlx_array_free(kv);
    const vv = try sliceAxis4(v, 2, g, seq, s);
    defer _ = mlx.mlx_array_free(vv);
    const kg = try sliceAxis4(k, 2, 0, g, s);
    defer _ = mlx.mlx_array_free(kg);
    const vg = try sliceAxis4(v, 2, 0, g, s);
    defer _ = mlx.mlx_array_free(vg);

    // [1,H,Sv,hd] -> [B, H, L, hd] with the pattern axis folded into batch:
    // spatial B=t, L=f (perm keeps (t) outermost); temporal B=f, L=t.
    const fold = struct {
        fn go(x: mlx.mlx_array, nh_: c_int, t_: c_int, f_: c_int, hd_: c_int, mode: SparseMode, s_: S) !mlx.mlx_array {
            const r = try reshape(x, &[_]c_int{ nh_, t_, f_, hd_ }, s_);
            defer _ = mlx.mlx_array_free(r);
            const perm: [4]c_int = if (mode == .spatial) .{ 1, 0, 2, 3 } else .{ 2, 0, 1, 3 };
            const tr = try transpose(r, &perm, s_);
            defer _ = mlx.mlx_array_free(tr);
            return contig(tr, s_);
        }
    }.go;
    const qb = try fold(qv, nh, t, f, hd, spec.mode, s);
    defer _ = mlx.mlx_array_free(qb);
    const kb = try fold(kv, nh, t, f, hd, spec.mode, s);
    defer _ = mlx.mlx_array_free(kb);
    const vb = try fold(vv, nh, t, f, hd, spec.mode, s);
    defer _ = mlx.mlx_array_free(vb);

    // Strip keys broadcast to every batch element and appended to the keys.
    const nb: c_int = if (spec.mode == .spatial) t else f;
    const bshape = [_]c_int{ nb, nh, g, hd };
    const bc = struct {
        fn go(x: mlx.mlx_array, shape: []const c_int, s_: S) !mlx.mlx_array {
            const r3 = try reshape(x, &[_]c_int{ 1, shape[1], shape[2], shape[3] }, s_);
            defer _ = mlx.mlx_array_free(r3);
            var b = mlx.mlx_array_new();
            defer _ = mlx.mlx_array_free(b);
            try mlx.check(mlx.mlx_broadcast_to(&b, r3, shape.ptr, shape.len, s_));
            return contig(b, s_);
        }
    }.go;
    const kgb = try bc(kg, &bshape, s);
    defer _ = mlx.mlx_array_free(kgb);
    const vgb = try bc(vg, &bshape, s);
    defer _ = mlx.mlx_array_free(vgb);
    const kcat = try concat(&[_]mlx.mlx_array{ kb, kgb }, 2, s);
    defer _ = mlx.mlx_array_free(kcat);
    const vcat = try concat(&[_]mlx.mlx_array{ vb, vgb }, 2, s);
    defer _ = mlx.mlx_array_free(vcat);

    var ob = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(ob);
    try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&ob, qb, kcat, vcat, scale, "", null_a, null_a, s));

    // Unfold back to [1, H, Sv, hd] in packed row order.
    const inv_perm: [4]c_int = if (spec.mode == .spatial) .{ 1, 0, 2, 3 } else .{ 1, 2, 0, 3 };
    const otr = try transpose(ob, &inv_perm, s);
    defer _ = mlx.mlx_array_free(otr);
    const oc = try contig(otr, s);
    defer _ = mlx.mlx_array_free(oc);
    const ov = try reshape(oc, &[_]c_int{ 1, nh, t * f, hd }, s);
    defer _ = mlx.mlx_array_free(ov);

    return concat(&[_]mlx.mlx_array{ og, ov }, 2, s);
}

/// sliceAxis for the fixed 4-D case (keeps the [1,H,·,hd] shape).
fn sliceAxis4(x: mlx.mlx_array, axis: usize, lo: c_int, hi: c_int, s: S) !mlx.mlx_array {
    const shp = mlx.getShape(x);
    var start = [_]c_int{ 0, 0, 0, 0 };
    var stop = [_]c_int{ shp[0], shp[1], shp[2], shp[3] };
    const step = [_]c_int{ 1, 1, 1, 1 };
    start[axis] = lo;
    stop[axis] = hi;
    var o = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o);
    try mlx.check(mlx.mlx_slice(&o, x, &start, 4, &stop, 4, &step, 4, s));
    return contig(o, s);
}

/// x [S, hidden] -> [S, hidden]. Full bidirectional attention (no mask): this
/// is a diffusion transformer, every token sees every other.
///
/// `ablate` is `.none` everywhere except the profile ladder; `.sdpa` passes v
/// through in place of the attention output (same shape, projections intact).
fn attnForward(aw: *const AttnW, x: mlx.mlx_array, cfg: Config, rope: ?RopeTables, ablate: Ablate, sparse: ?SparseSpec, s: S) !mlx.mlx_array {
    const n: c_int = @intCast(mlx.getShape(x)[0]);
    const h: c_int = @intCast(cfg.num_attention_heads);
    const hd: c_int = @intCast(cfg.attention_head_dim);
    const half: c_int = @intCast(cfg.rotDim() / 2);

    const qkv = try aw.qkv.forward(x, null, s);
    defer _ = mlx.mlx_array_free(qkv);
    var parts: [3]mlx.mlx_array = undefined;
    try splitEqual(qkv, 3, 1, &parts, s);
    defer for (&parts) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    var qkvn: [3]mlx.mlx_array = undefined;
    var built: usize = 0;
    errdefer for (qkvn[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    for (0..3) |i| {
        // [S, inner] -> [1, S, H, hd]
        const v4 = try reshape(parts[i], &[_]c_int{ 1, n, h, hd }, s);
        if (i == 2) {
            qkvn[i] = v4;
            built += 1;
            continue;
        }
        defer _ = mlx.mlx_array_free(v4);
        // Per-head RMSNorm over head_dim, THEN rope — that order is the
        // reference's fused kernel, and swapping it changes the result.
        const nw = if (i == 0) aw.q_norm else aw.k_norm;
        const normed = try rmsNormLast(v4, nw, cfg.qk_norm_eps, s);
        if (rope) |rp| {
            defer _ = mlx.mlx_array_free(normed);
    qkvn[i] = try applyRopePub(normed, rp, half, hd, s);
        } else {
            qkvn[i] = normed;
        }
        built += 1;
    }
    defer for (&qkvn) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    // [1,S,H,hd] -> [1,H,S,hd] for SDPA
    var t: [3]mlx.mlx_array = undefined;
    for (0..3) |i| {
        const tr = try transpose(qkvn[i], &[_]c_int{ 0, 2, 1, 3 }, s);
        defer _ = mlx.mlx_array_free(tr);
        t[i] = try contig(tr, s);
    }
    defer for (&t) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };

    const scale: f32 = 1.0 / @sqrt(@as(f32, @floatFromInt(cfg.attention_head_dim)));
    var attn: mlx.mlx_array = undefined;
    if (ablate == .sdpa) {
        attn = try contig(t[2], s);
    } else if (ablate == .sdpa_dep) {
        const sum_qk = try addA(t[0], t[1], s);
        defer _ = mlx.mlx_array_free(sum_qk);
        const sum3 = try addA(sum_qk, t[2], s);
        defer _ = mlx.mlx_array_free(sum3);
        const third = try scalarLike(1.0 / 3.0, sum3, s);
        defer _ = mlx.mlx_array_free(third);
        attn = try mulA(sum3, third, s);
    } else if (sparse != null and sparse.?.mode != .dense) {
        attn = try sparseAttend(t[0], t[1], t[2], sparse.?, scale, s);
    } else {
        var o = mlx.mlx_array_new();
        errdefer _ = mlx.mlx_array_free(o);
        const null_a = mlx.mlx_array{ .ctx = null };
        try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&o, t[0], t[1], t[2], scale, "", null_a, null_a, s));
        attn = o;
    }
    defer _ = mlx.mlx_array_free(attn);

    // [1,H,S,hd] -> [S, inner]
    const back = try transpose(attn, &[_]c_int{ 0, 2, 1, 3 }, s);
    defer _ = mlx.mlx_array_free(back);
    const bc = try contig(back, s);
    defer _ = mlx.mlx_array_free(bc);
    const flat = try reshape(bc, &[_]c_int{ n, h * hd }, s);
    defer _ = mlx.mlx_array_free(flat);
    return aw.out.forward(flat, null, s);
}

/// fc1 emits gate and up FUSED as [S, 2*ffn]; SwiGLU is silu(gate) * up.
fn mlpForward(mw: *const MlpW, x: mlx.mlx_array, s: S) !mlx.mlx_array {
    const y = try mw.fc1.forward(x, null, s);
    defer _ = mlx.mlx_array_free(y);
    var halves: [2]mlx.mlx_array = undefined;
    try splitEqual(y, 2, 1, &halves, s);
    defer for (&halves) |*p| {
        _ = mlx.mlx_array_free(p.*);
    };
    const g = try siluA(halves[0], s);
    defer _ = mlx.mlx_array_free(g);
    const act = try mulA(g, halves[1], s);
    defer _ = mlx.mlx_array_free(act);
    return mw.fc2.forward(act, null, s);
}

// ── Modulation over packed segments ─────────────────────────────────────────

/// A contiguous run of rows sharing one AdaLN modulation row.
pub const ModRun = struct { start: u32, end: u32, mod_row: u32 };

/// `h[a:b] = h[a:b] * (1 + scale[row]) + shift[row]`, applied per run.
///
/// Done by slicing rather than gathering: a gather would materialize
/// [S, hidden] per modulation tensor (81 MB each at the dev shape, six per
/// block), while the runs number a handful.
fn modScaleShift(h: mlx.mlx_array, shift: mlx.mlx_array, scale: mlx.mlx_array, runs: []const ModRun, a: std.mem.Allocator, s: S) !mlx.mlx_array {
    var pieces = try a.alloc(mlx.mlx_array, runs.len);
    defer a.free(pieces);
    var built: usize = 0;
    errdefer for (pieces[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    const one = try scalarLike(1.0, h, s);
    defer _ = mlx.mlx_array_free(one);

    for (runs, 0..) |r, i| {
        const seg = try sliceRows(h, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(seg);
        const sc = try sliceRows(scale, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(sc);
        const sh = try sliceRows(shift, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(sh);
        const sc1 = try addA(sc, one, s);
        defer _ = mlx.mlx_array_free(sc1);
        const m = try mulA(seg, sc1, s);
        defer _ = mlx.mlx_array_free(m);
        pieces[i] = try addA(m, sh, s);
        built += 1;
    }
    defer for (pieces) |p| {
        _ = mlx.mlx_array_free(p);
    };
    return concat(pieces, 0, s);
}

/// `x[a:b] += other[a:b] * gate[row]`, applied per run.
fn modGate(x: mlx.mlx_array, gate: mlx.mlx_array, other: mlx.mlx_array, runs: []const ModRun, a: std.mem.Allocator, s: S) !mlx.mlx_array {
    var pieces = try a.alloc(mlx.mlx_array, runs.len);
    defer a.free(pieces);
    var built: usize = 0;
    errdefer for (pieces[0..built]) |p| {
        _ = mlx.mlx_array_free(p);
    };
    for (runs, 0..) |r, i| {
        const xs = try sliceRows(x, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(xs);
        const os = try sliceRows(other, @intCast(r.start), @intCast(r.end), s);
        defer _ = mlx.mlx_array_free(os);
        const g = try sliceRows(gate, @intCast(r.mod_row), @intCast(r.mod_row + 1), s);
        defer _ = mlx.mlx_array_free(g);
        const m = try mulA(os, g, s);
        defer _ = mlx.mlx_array_free(m);
        pieces[i] = try addA(xs, m, s);
        built += 1;
    }
    defer for (pieces) |p| {
        _ = mlx.mlx_array_free(p);
    };
    return concat(pieces, 0, s);
}

// ── Timestep rows ───────────────────────────────────────────────────────────

pub const MAX_UNIQUE_T = 4;

/// The distinct timesteps a forward needs, and the per-run modulation rows.
///
/// The reference derives these analytically rather than carrying a per-token
/// timestep tensor: text and video ride the video timestep, audio rides its own
/// shifted one, and condition rows pin near 1 (they are re-injected clean every
/// step, never denoised).
pub const TimestepPlan = struct {
    unique_t: [MAX_UNIQUE_T]f64,
    n_unique: usize,
    runs: []ModRun,
    allocator: std.mem.Allocator,

    pub fn deinit(self: *TimestepPlan) void {
        self.allocator.free(self.runs);
    }
};

pub const CondNoiseAug = struct {
    visual: f64 = VISUAL_COND_TIMESTEP,
    audio: f64 = AUDIO_COND_TIMESTEP,
};

pub fn buildTimestepPlan(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    sigma_v: f64,
    shift_v: f64,
    shift_a: f64,
    aug: CondNoiseAug,
) !TimestepPlan {
    const t_v = 1.0 - sigma_v;
    const t_a = 1.0 - timeShiftSigma(sigma_v, shift_v, shift_a);

    var uniq: [MAX_UNIQUE_T]f64 = undefined;
    var n: usize = 0;
    const add = struct {
        fn f(buf: *[MAX_UNIQUE_T]f64, cnt: *usize, v: f64) void {
            for (buf[0..cnt.*]) |e| if (e == v) return;
            buf[cnt.*] = v;
            cnt.* += 1;
        }
    }.f;

    var has_vis_cond = false;
    var has_aud_cond = false;
    for (layout.segments) |seg| switch (seg.kind) {
        .cond, .ref_img => has_vis_cond = true,
        .ref_audio => has_aud_cond = true,
        else => {},
    };
    add(&uniq, &n, t_v);
    add(&uniq, &n, t_a);
    if (has_vis_cond) add(&uniq, &n, @max(t_v, aug.visual));
    if (has_aud_cond) add(&uniq, &n, @max(t_a, aug.audio));
    std.mem.sort(f64, uniq[0..n], {}, std.sort.asc(f64));

    const rowOf = struct {
        fn f(buf: []const f64, v: f64) u32 {
            for (buf, 0..) |e, i| if (e == v) return @intCast(i);
            unreachable;
        }
    }.f;

    var runs = try allocator.alloc(ModRun, layout.segments.len);
    errdefer allocator.free(runs);
    for (layout.segments, 0..) |seg, i| {
        const t = switch (seg.kind) {
            .text, .video => t_v,
            .audio => t_a,
            .cond, .ref_img => @max(t_v, aug.visual),
            .ref_audio => @max(t_a, aug.audio),
        };
        // Row = t_row * modalities + tag. The `* 3` is the AdaLN reshape's
        // modality stride, not an arbitrary constant.
        runs[i] = .{
            .start = seg.start,
            .end = seg.end,
            .mod_row = rowOf(uniq[0..n], t) * 3 + seg.kind.modalityTag(),
        };
    }
    return .{ .unique_t = uniq, .n_unique = n, .runs = runs, .allocator = allocator };
}

// ── Profiling ablation ──────────────────────────────────────────────────────
//
// Phase-0 cost attribution WITHOUT inserting syncs: an arm removes one
// component from the step graph while keeping every shape, so the step-time
// delta against the `.none` baseline prices that component at the loop's own
// eval cadence. The per-phase-eval profiler lesson (MLX_SERVE_DECODE_PROFILE)
// is exactly what this avoids — inserted evals destroy pipelining and inflate
// what they measure.

pub const Ablate = enum {
    /// Full forward — the baseline arm.
    none,
    /// SDPA passes v through: prices the attention KERNEL alone (projections
    /// run) — but q/k become DEAD and lazy-graph pruning removes their norm/
    /// rope/transpose chains too, so this arm OVERSTATES the kernel.
    sdpa,
    /// SDPA replaced by (q+k+v)/3: every input branch stays LIVE, only the
    /// attention kernel itself is removed. The honest SDPA price is
    /// (none - sdpa_dep); (sdpa_dep - sdpa) is the q/k branch cost the plain
    /// arm silently pruned.
    sdpa_dep,
    /// The whole attention block is identity: prices qkv/SDPA/out together.
    attn,
    /// The MLP is identity: prices fc1/SwiGLU/fc2.
    mlp,
    /// Block AdaLN replaced by zero modulation: prices the 13B AdaLN weight
    /// read + its GEMM.
    adaln,
};

pub const AblateMode = union(enum) { off, ladder, fixed: Ablate };

/// MINIMAX_H3_ABLATE: "ladder" cycles arms inside ONE run (one TE+DiT load),
/// a bare arm name pins it, anything else is off. The caller logs a warning on
/// junk — a typo'd env measuring the wrong thing is the silent-flag-eater class.
pub fn ablateModeFrom(raw: ?[]const u8) AblateMode {
    const v = raw orelse return .off;
    if (v.len == 0) return .off;
    if (std.mem.eql(u8, v, "ladder")) return .ladder;
    inline for (@typeInfo(Ablate).@"enum".field_names) |n| {
        if (std.mem.eql(u8, v, n)) return .{ .fixed = @field(Ablate, n) };
    }
    return .off;
}

/// Ladder schedule: 2 warmup steps (graph build + JIT land in step 0), then 3
/// steps per arm starting with a measured `.none` baseline; past the ladder it
/// degrades to `.none` so an over-long STEPS setting stays harmless.
pub fn ladderArmForStep(i: usize) Ablate {
    if (i < 2) return .none;
    const arms = [_]Ablate{ .none, .sdpa, .attn, .mlp, .adaln };
    const idx = (i - 2) / 3;
    return if (idx < arms.len) arms[idx] else .none;
}

/// `buildTimestepPlan`, but with every run's modulation row remapped into a
/// GLOBAL sorted schedule table — the shape AdaLN precompute serves rows from.
/// A timestep missing from the table is a LOUD error, never a wrong row.
pub fn buildTimestepPlanGlobal(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    sigma_v: f64,
    shift_v: f64,
    shift_a: f64,
    aug: CondNoiseAug,
    global_ts: []const f64,
) !TimestepPlan {
    var p = try buildTimestepPlan(allocator, layout, sigma_v, shift_v, shift_a, aug);
    errdefer p.deinit();
    for (p.runs) |*r| {
        const t = p.unique_t[r.mod_row / 3];
        const tag = r.mod_row % 3;
        const gi = for (global_ts, 0..) |g, i| {
            if (g == t) break i;
        } else return error.TimestepNotInSchedule;
        r.mod_row = @as(u32, @intCast(gi)) * 3 + tag;
    }
    return p;
}

/// The union of every step's unique timesteps, sorted ascending — computed by
/// running the SAME per-step plan arithmetic, so the f64s are bit-identical to
/// what the sampling loop will look up.
pub fn collectScheduleTs(
    allocator: std.mem.Allocator,
    layout: *const PackedLayout,
    sigmas: []const f64,
    shift_v: f64,
    shift_a: f64,
    aug: CondNoiseAug,
) ![]f64 {
    var list: std.ArrayList(f64) = .empty;
    errdefer list.deinit(allocator);
    for (sigmas) |sig| {
        var p = try buildTimestepPlan(allocator, layout, sig, shift_v, shift_a, aug);
        defer p.deinit();
        for (p.unique_t[0..p.n_unique]) |t| {
            const seen = for (list.items) |e| {
                if (e == t) break true;
            } else false;
            if (!seen) try list.append(allocator, t);
        }
    }
    const out = try list.toOwnedSlice(allocator);
    std.mem.sort(f64, out, {}, std.sort.asc(f64));
    return out;
}

// ── Sparse video attention (training-free, SVG/STA-style) ───────────────────
//
// Full attention over the packed sequence is O(S²) and ~70% of a 768p step.
// Video-DiT attention mass concentrates in two patterns: SPATIAL (within the
// same frame) and TEMPORAL (same patch across frames). Each video query can
// attend to its pattern's keys plus the GLOBAL STRIP (text/cond/audio rows —
// they are few and carry the conditioning), while strip queries keep full
// attention. Softmax is over the reduced key set — a training-free
// approximation whose quality is judged by clips, not asserted.
//
// Layer policy (`MINIMAX_H3_SPARSE_ATTN`): "mix" alternates spatial/temporal
// per layer with dense anchor layers at the ends and middle; "spatial"/
// "temporal" force one pattern everywhere (debug); unset/"" = off.

pub const SparseMode = enum { dense, spatial, temporal };

pub const SparsePolicy = enum { off, mix, spatial, temporal };

pub fn sparsePolicyFrom(raw: ?[]const u8) SparsePolicy {
    const v = raw orelse return .off;
    if (v.len == 0 or std.mem.eql(u8, v, "0")) return .off;
    if (std.mem.eql(u8, v, "mix")) return .mix;
    if (std.mem.eql(u8, v, "spatial")) return .spatial;
    if (std.mem.eql(u8, v, "temporal")) return .temporal;
    return .off;
}

/// Which pattern a layer runs under a policy. Anchor layers (first two,
/// middle two, last two) stay DENSE under "mix" — they re-integrate global
/// structure the sparse layers cannot see.
pub fn sparseModeForLayer(layer: usize, n_layers: usize, policy: SparsePolicy) SparseMode {
    switch (policy) {
        .off => return .dense,
        .spatial => return .spatial,
        .temporal => return .temporal,
        .mix => {
            const mid = n_layers / 2;
            if (layer < 2 or layer + 2 >= n_layers or layer == mid or layer == mid + 1) return .dense;
            return if (layer % 2 == 0) .spatial else .temporal;
        },
    }
}

/// Geometry the sparse core needs: the video segment is the LAST `t*f` rows
/// of the packed sequence; everything before it is the global strip.
pub const SparseSpec = struct {
    mode: SparseMode,
    /// Latent frames.
    t: u32,
    /// Rows per frame (h/2 * w/2).
    f: u32,
    /// First video row == strip length.
    video_start: u32,
};

// ── Attention broadcast (PAB-style) ─────────────────────────────────────────
//
// Video-DiT attention outputs drift SLOWLY across adjacent mid-schedule steps
// (Pyramid Attention Broadcast's finding, reproduced here by the step-cache's
// own gate statistics), while modulation and the MLP react faster. On
// non-refresh steps every block reuses its cached attention OUTPUT (post
// out-proj) and skips norm1/mod/qkv/SDPA/out entirely — at 768p that branch
// is ~70% of the step. Gating stays per-STEP and deterministic: warmup and
// tail steps always recompute (structure forms early, detail lands late).

pub const AttnBroadcast = struct {
    allocator: std.mem.Allocator,
    /// Per block: the cached attention output [S, hidden]; null ctx = empty.
    blocks: []mlx.mlx_array,

    pub fn init(allocator: std.mem.Allocator, n_blocks: usize) !AttnBroadcast {
        const blocks = try allocator.alloc(mlx.mlx_array, n_blocks);
        for (blocks) |*b| b.* = .{ .ctx = null };
        return .{ .allocator = allocator, .blocks = blocks };
    }
    pub fn deinit(self: *AttnBroadcast) void {
        for (self.blocks) |b| if (b.ctx != null) {
            _ = mlx.mlx_array_free(b);
        };
        self.allocator.free(self.blocks);
    }
};

/// Refresh schedule: k<=1 disables broadcast (always refresh); otherwise the
/// first 4 and last 2 steps always recompute, and every k-th step in between.
pub fn attnBroadcastRefresh(i: usize, steps: u32, k: u32) bool {
    if (k <= 1) return true;
    if (i < 4) return true;
    if (i + 2 >= steps) return true;
    return (i - 4) % k == 0;
}

// ── Model ───────────────────────────────────────────────────────────────────

/// Whole-schedule AdaLN tables: per block, the 6 modulation arrays evaluated
/// at EVERY timestep the sampling schedule will visit ([n_ts*3, hidden] each,
/// rows indexed `global_t_row * 3 + modality`), plus the final layer's pair.
/// ~12 MB/block bf16 at 30 steps — against the 13.04B AdaLN parameters (39%
/// of the model) they replace. A MEMORY lever, not a speed one: the per-step
/// AdaLN cost measured ~0 in the Phase-0 ladder.
pub const AdalnTables = struct {
    allocator: std.mem.Allocator,
    ts: []f64,
    blocks: [][6]mlx.mlx_array,
    final: [2]mlx.mlx_array,

    pub fn deinit(self: *AdalnTables) void {
        for (self.blocks) |*six| {
            for (six) |a2| _ = mlx.mlx_array_free(a2);
        }
        self.allocator.free(self.blocks);
        for (self.final) |a2| _ = mlx.mlx_array_free(a2);
        self.allocator.free(self.ts);
        self.* = undefined;
    }
};

pub const Model = struct {
    allocator: std.mem.Allocator,
    cfg: Config,
    dtype: mlx.mlx_dtype,
    /// Profiling arm for the NEXT forward; `.none` in production (the field is
    /// only ever set by the profile ladder in `generate`).
    ablate: Ablate,
    /// Sparse-attention layer policy (`MINIMAX_H3_SPARSE_ATTN`); `.off` until
    /// `generate` opts in.
    sparse_policy: SparsePolicy,

    video_patch_w: mlx.mlx_array, // fp32 island
    video_patch_b: mlx.mlx_array,
    audio_patch_w: mlx.mlx_array,
    audio_patch_b: mlx.mlx_array,
    condition_proj: MfLinear,
    condition_bias: mlx.mlx_array,

    te_in_w: mlx.mlx_array, // time embedder, fp32 island
    te_in_b: mlx.mlx_array,
    te_out_w: mlx.mlx_array,
    te_out_b: mlx.mlx_array,
    inv_freq: mlx.mlx_array,

    refiner: []RefinerBlockW,
    refiner_final_norm: mlx.mlx_array,
    blocks: []BlockW,

    final_norm: mlx.mlx_array,
    /// Null after AdaLN precompute (folded into `adaln_tables.final`).
    final_adaln: ?AdalnW,
    /// Whole-schedule AdaLN tables (see `precomputeAdaln`); null = per-step
    /// weight-based modulation, the load-time default until generate opts in.
    adaln_tables: ?AdalnTables,
    video_out_w: mlx.mlx_array, // fp32 island
    video_out_b: mlx.mlx_array,
    audio_out_w: mlx.mlx_array,
    audio_out_b: mlx.mlx_array,

    pub fn load(allocator: std.mem.Allocator, w: *const Weights, cfg: Config, dt: mlx.mlx_dtype, s: S) !Model {
        var m: Model = undefined;
        m.allocator = allocator;
        m.cfg = cfg;
        m.dtype = dt;
        m.ablate = .none;
        m.sparse_policy = .off;

        const f32t = mlx.mlx_dtype.float32;
        // These stay fp32 because the CHECKPOINT stores them fp32 — the patch
        // projections and output heads are its dense islands, and narrowing
        // them is the MageFlow precision class.
        m.video_patch_w = try ownWeightAs(w, allocator, "video_patch_proj", ".weight", f32t, s);
        m.video_patch_b = try ownWeightAs(w, allocator, "video_patch_proj", ".bias", f32t, s);
        m.audio_patch_w = try ownWeightAs(w, allocator, "audio_patch_proj", ".weight", f32t, s);
        m.audio_patch_b = try ownWeightAs(w, allocator, "audio_patch_proj", ".bias", f32t, s);
        m.condition_proj = try MfLinear.load(w, allocator, "condition_proj", cfg.text_dim, dt, s);
        m.condition_bias = try ownWeightAs(w, allocator, "condition_proj", ".bias", dt, s);

        m.te_in_w = try ownWeightAs(w, allocator, "time_embedder.proj_in", ".weight", f32t, s);
        m.te_in_b = try ownWeightAs(w, allocator, "time_embedder.proj_in", ".bias", f32t, s);
        m.te_out_w = try ownWeightAs(w, allocator, "time_embedder.proj_out", ".weight", f32t, s);
        m.te_out_b = try ownWeightAs(w, allocator, "time_embedder.proj_out", ".bias", f32t, s);
        m.inv_freq = try ownWeightAs(w, allocator, "rope", ".inv_freq", f32t, s);

        m.refiner = try allocator.alloc(RefinerBlockW, cfg.token_refiner_num_layers);
        for (m.refiner, 0..) |*b, i| b.* = try RefinerBlockW.load(w, allocator, @intCast(i), cfg, dt, s);
        m.refiner_final_norm = try ownWeightAs(w, allocator, "token_refiner.final_norm", ".weight", dt, s);

        m.blocks = try allocator.alloc(BlockW, cfg.num_layers);
        for (m.blocks, 0..) |*b, i| b.* = try BlockW.load(w, allocator, @intCast(i), cfg, dt, s);

        m.final_norm = try ownWeightAs(w, allocator, "final_layer.norm", ".weight", dt, s);
        m.final_adaln = try AdalnW.load(w, allocator, "final_layer.adaln_proj", cfg, 2, 1, dt, s);
        m.adaln_tables = null;
        m.video_out_w = try ownWeightAs(w, allocator, "final_layer.video_out", ".weight", f32t, s);
        m.video_out_b = try ownWeightAs(w, allocator, "final_layer.video_out", ".bias", f32t, s);
        m.audio_out_w = try ownWeightAs(w, allocator, "final_layer.audio_out", ".weight", f32t, s);
        m.audio_out_b = try ownWeightAs(w, allocator, "final_layer.audio_out", ".bias", f32t, s);
        return m;
    }

    pub fn deinit(self: *Model) void {
        for ([_]mlx.mlx_array{
            self.video_patch_w, self.video_patch_b, self.audio_patch_w, self.audio_patch_b,
            self.condition_bias, self.te_in_w,      self.te_in_b,       self.te_out_w,
            self.te_out_b,      self.inv_freq,      self.final_norm,    self.video_out_w,
            self.video_out_b,   self.audio_out_w,   self.audio_out_b,   self.refiner_final_norm,
        }) |a| _ = mlx.mlx_array_free(a);
        self.condition_proj.deinit();
        for (self.refiner) |*b| b.deinit();
        self.allocator.free(self.refiner);
        for (self.blocks) |*b| b.deinit();
        self.allocator.free(self.blocks);
        if (self.final_adaln) |*fa| fa.deinit();
        if (self.adaln_tables) |*t| t.deinit();
    }

    /// Force-materialize every weight in ONE eval. Without this the load is
    /// lazy and the 35-64 GB read lands inside step 1, which both hides the
    /// load phase from any profile and makes the first step read as a
    /// regression. Explicit rather than reflective: a missed field here only
    /// shifts a few ms of attribution, never a budget (unlike the dsv4 case).
    pub fn evalWeights(self: *const Model) !void {
        const vec = mlx.mlx_vector_array_new();
        defer _ = mlx.mlx_vector_array_free(vec);
        const push = struct {
            fn arr(v: mlx.mlx_vector_array, x: mlx.mlx_array) void {
                if (x.ctx != null) _ = mlx.mlx_vector_array_append_value(v, x);
            }
            fn lin(v: mlx.mlx_vector_array, l: *const MfLinear) void {
                arr(v, l.w);
                arr(v, l.scales);
                arr(v, l.biases);
            }
            fn at(v: mlx.mlx_vector_array, w: *const AttnW) void {
                lin(v, &w.qkv);
                arr(v, w.q_norm);
                arr(v, w.k_norm);
                lin(v, &w.out);
            }
            fn ml(v: mlx.mlx_vector_array, w: *const MlpW) void {
                lin(v, &w.fc1);
                lin(v, &w.fc2);
            }
        };
        for ([_]mlx.mlx_array{
            self.video_patch_w, self.video_patch_b, self.audio_patch_w, self.audio_patch_b,
            self.condition_bias, self.te_in_w,      self.te_in_b,       self.te_out_w,
            self.te_out_b,      self.inv_freq,      self.final_norm,    self.video_out_w,
            self.video_out_b,   self.audio_out_w,   self.audio_out_b,   self.refiner_final_norm,
        }) |x| push.arr(vec, x);
        push.lin(vec, &self.condition_proj);
        for (self.refiner) |*b| {
            push.arr(vec, b.norm1);
            push.arr(vec, b.norm2);
            push.at(vec, &b.attn);
            push.ml(vec, &b.mlp);
        }
        for (self.blocks) |*b| {
            push.arr(vec, b.norm1);
            push.arr(vec, b.norm2);
            push.at(vec, &b.attn);
            push.ml(vec, &b.mlp);
            if (b.adaln) |*ad| {
                push.lin(vec, &ad.linear);
                push.arr(vec, ad.bias);
            }
        }
        if (self.final_adaln) |*fa| {
            push.lin(vec, &fa.linear);
            push.arr(vec, fa.bias);
        }
        try mlx.check(mlx.mlx_eval(vec));
    }

    /// Materialize AdaLN for the whole schedule and RELEASE the 13B AdaLN
    /// weights. Must run while the trunk is still LAZY (before `evalWeights`):
    /// each block's AdaLN weight materializes only inside its own forward here
    /// and is freed immediately after, so the transient peak is one block's
    /// 260M params — never the 13 GB the weights would cost resident.
    ///
    /// NOT bit-identical to per-step modulation: the AdaLN GEMM runs at
    /// M = n_ts instead of M = 2-3, and kernel selection differs by shape
    /// (the sanctioned qmv-vs-qmm class). Kill: MINIMAX_H3_ADALN_PRECOMPUTE=0.
    pub fn precomputeAdaln(self: *Model, ts: []const f64, s: S) !void {
        std.debug.assert(self.adaln_tables == null);
        const a = self.allocator;
        const t_emb32 = try self.timeEmbed(ts, s);
        defer _ = mlx.mlx_array_free(t_emb32);
        const t_emb = try astype(t_emb32, self.dtype, s);
        defer _ = mlx.mlx_array_free(t_emb);

        var tables = try a.alloc([6]mlx.mlx_array, self.blocks.len);
        errdefer a.free(tables);
        var built: usize = 0;
        errdefer for (tables[0..built]) |*six| {
            for (six) |x| _ = mlx.mlx_array_free(x);
        };
        for (self.blocks) |*b| {
            var mods: [6]mlx.mlx_array = undefined;
            try b.adaln.?.forward(t_emb, self.cfg, true, &mods, s);
            const vec = mlx.mlx_vector_array_new();
            defer _ = mlx.mlx_vector_array_free(vec);
            for (mods) |m2| _ = mlx.mlx_vector_array_append_value(vec, m2);
            try mlx.check(mlx.mlx_eval(vec));
            tables[built] = mods;
            built += 1;
            // Free the weight NOW so only one block's AdaLN is ever resident.
            b.adaln.?.deinit();
            b.adaln = null;
        }
        var fmods: [2]mlx.mlx_array = undefined;
        try self.final_adaln.?.forward(t_emb, self.cfg, true, &fmods, s);
        const fvec = mlx.mlx_vector_array_new();
        defer _ = mlx.mlx_vector_array_free(fvec);
        for (fmods) |m2| _ = mlx.mlx_vector_array_append_value(fvec, m2);
        try mlx.check(mlx.mlx_eval(fvec));
        self.final_adaln.?.deinit();
        self.final_adaln = null;
        _ = mlx.mlx_clear_cache();

        const ts_copy = try a.dupe(f64, ts);
        errdefer a.free(ts_copy);
        self.adaln_tables = .{ .allocator = a, .ts = ts_copy, .blocks = tables, .final = fmods };
    }

    /// Sinusoidal timestep embedding, fp32 throughout, COS BEFORE SIN.
    /// The concat order is not cosmetic: swapping the halves silently shifts
    /// every modulation the model produces.
    fn timeEmbed(self: *const Model, t_vals: []const f64, s: S) !mlx.mlx_array {
        const half = self.cfg.timestep_input_dim / 2;
        const m = t_vals.len;
        const buf = try self.allocator.alloc(f32, m * @as(usize, half) * 2);
        defer self.allocator.free(buf);
        const log10k = @log(10000.0);
        for (t_vals, 0..) |t, i| {
            for (0..half) |j| {
                const freq = @exp(-log10k * @as(f64, @floatFromInt(j)) / @as(f64, @floatFromInt(half)));
                const arg = t * freq;
                buf[i * half * 2 + j] = @floatCast(@cos(arg));
                buf[i * half * 2 + half + j] = @floatCast(@sin(arg));
            }
        }
        const shape = [_]c_int{ @intCast(m), @intCast(half * 2) };
        const emb = mlx.mlx_array_new_data(buf.ptr, &shape, 2, mlx.mlx_dtype.float32);
        defer _ = mlx.mlx_array_free(emb);
        const h1 = try denseLinear(emb, self.te_in_w, self.te_in_b, s);
        defer _ = mlx.mlx_array_free(h1);
        const a1 = try siluA(h1, s);
        defer _ = mlx.mlx_array_free(a1);
        return denseLinear(a1, self.te_out_w, self.te_out_b, s);
    }

    /// Qwen states [L, text_dim] -> refined [L, hidden].
    pub fn refineText(self: *const Model, text_states: mlx.mlx_array, s: S) !mlx.mlx_array {
        const hidden: usize = @intCast(mlx.getShape(text_states)[1]);
        if (hidden == self.cfg.hidden_size) return contig(text_states, s);
        var h = try self.condition_proj.forward(text_states, self.condition_bias, s);
        errdefer _ = mlx.mlx_array_free(h);
        for (self.refiner) |*b| {
            const n1 = try rmsNormLast(h, b.norm1, self.cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n1);
            const at = try attnForward(&b.attn, n1, self.cfg, null, .none, null, s);
            defer _ = mlx.mlx_array_free(at);
            const h2 = try addA(h, at, s);
            _ = mlx.mlx_array_free(h);
            h = h2;
            const n2 = try rmsNormLast(h, b.norm2, self.cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n2);
            const mo = try mlpForward(&b.mlp, n2, s);
            defer _ = mlx.mlx_array_free(mo);
            const h3 = try addA(h, mo, s);
            _ = mlx.mlx_array_free(h);
            h = h3;
        }
        const out = try rmsNormLast(h, self.refiner_final_norm, self.cfg.final_norm_eps, s);
        _ = mlx.mlx_array_free(h);
        return out;
    }

    pub const Output = struct {
        /// Velocity for the video stream, [n_video_rows, videoPatchDim].
        video: mlx.mlx_array,
        /// Velocity for the audio stream, [n_audio_rows, audio_latents_dim],
        /// ALREADY scaled by d(sigma_a)/d(sigma_v).
        audio: mlx.mlx_array,

        pub fn deinit(self: *Output) void {
            _ = mlx.mlx_array_free(self.video);
            _ = mlx.mlx_array_free(self.audio);
        }
    };

    /// One denoising forward over the packed sequence.
    ///
    /// `video_rows` covers EVERY video-stream row in packed order (condition
    /// rows included), likewise `audio_rows`; the caller composes them from the
    /// noisy latents and the clean conditions using `layout.img_update`.
    pub fn forward(
        self: *const Model,
        layout: *const PackedLayout,
        plan: *const TimestepPlan,
        text_states: mlx.mlx_array, // [text_len, hidden] (already refined)
        video_rows: mlx.mlx_array, // [n_video_rows, videoPatchDim] f32
        audio_rows: mlx.mlx_array, // [n_audio_rows, audio_latents_dim] f32
        rope: RopeTables,
        sigma_v: f64,
        shift_v: f64,
        shift_a: f64,
        attn_bcast: ?*AttnBroadcast,
        attn_refresh: bool,
        s: S,
    ) !Output {
        const a = self.allocator;
        const cfg = self.cfg;

        // Embed the two latent streams through their fp32 patch projections.
        const ve32 = try denseLinear(video_rows, self.video_patch_w, self.video_patch_b, s);
        defer _ = mlx.mlx_array_free(ve32);
        const video_embed = try astype(ve32, self.dtype, s);
        defer _ = mlx.mlx_array_free(video_embed);
        const ae32 = try denseLinear(audio_rows, self.audio_patch_w, self.audio_patch_b, s);
        defer _ = mlx.mlx_array_free(ae32);
        const audio_embed = try astype(ae32, self.dtype, s);
        defer _ = mlx.mlx_array_free(audio_embed);

        // Assemble the packed stream segment by segment. Segments are
        // contiguous and each draws from exactly one embedding stream.
        var pieces = try a.alloc(mlx.mlx_array, layout.segments.len);
        defer a.free(pieces);
        var voff: c_int = 0;
        var aoff: c_int = 0;
        var built: usize = 0;
        errdefer for (pieces[0..built]) |p| {
            _ = mlx.mlx_array_free(p);
        };
        for (layout.segments, 0..) |seg, i| {
            const n: c_int = @intCast(seg.end - seg.start);
            switch (seg.kind.stream()) {
                .text => pieces[i] = try contig(text_states, s),
                .video => {
                    pieces[i] = try sliceRows(video_embed, voff, voff + n, s);
                    voff += n;
                },
                .audio => {
                    pieces[i] = try sliceRows(audio_embed, aoff, aoff + n, s);
                    aoff += n;
                },
            }
            built += 1;
        }
        var h = try concat(pieces, 0, s);
        for (pieces) |p| _ = mlx.mlx_array_free(p);
        errdefer _ = mlx.mlx_array_free(h);

        // t_emb is only needed when modulation still runs from weights; with
        // precomputed tables neither the embedder nor any AdalnW exists.
        var t_emb = mlx.mlx_array{ .ctx = null };
        defer if (t_emb.ctx != null) {
            _ = mlx.mlx_array_free(t_emb);
        };
        if (self.adaln_tables == null) {
            const t_emb32 = try self.timeEmbed(plan.unique_t[0..plan.n_unique], s);
            defer _ = mlx.mlx_array_free(t_emb32);
            t_emb = try astype(t_emb32, self.dtype, s);
        }

        // The `.adaln` profile arm replaces every block's modulation with one
        // shared zero tensor (shift=scale=gate=0, rows cover any mod_row), so
        // the arm's saving is exactly the AdaLN weight read + GEMM.
        var zero_mods = mlx.mlx_array{ .ctx = null };
        defer if (zero_mods.ctx != null) {
            _ = mlx.mlx_array_free(zero_mods);
        };
        if (self.ablate == .adaln) {
            const zrows: c_int = if (self.adaln_tables) |tt| @intCast(tt.ts.len * 3) else @intCast(MAX_UNIQUE_T * 3);
            try mlx.check(mlx.mlx_zeros(&zero_mods, &[_]c_int{ zrows, @intCast(cfg.hidden_size) }, 2, self.dtype, s));
        }

        for (self.blocks, 0..) |*b, bi| {
            var mods: [6]mlx.mlx_array = undefined;
            var mods_owned = true;
            if (self.ablate == .adaln) {
                for (&mods) |*p| p.* = try contig(zero_mods, s);
            } else if (self.adaln_tables) |tt| {
                mods = tt.blocks[bi]; // borrowed from the table
                mods_owned = false;
            } else {
                try b.adaln.?.forward(t_emb, cfg, true, &mods, s);
            }
            defer if (mods_owned) for (&mods) |*p| {
                _ = mlx.mlx_array_free(p.*);
            };
            // 0..5 = shift_msa, scale_msa, gate_msa, shift_mlp, scale_mlp, gate_mlp
            //
            // Attention branch: on a broadcast (non-refresh) step the whole
            // branch — norm1, modulation, qkv, SDPA, out-proj — is replaced by
            // the block's cached output from the last refresh; only the GATE
            // is re-applied at the current timestep (PAB semantics). Profile
            // arms bypass the cache so ablation stays honest.
            var at: mlx.mlx_array = undefined;
            var at_owned = true;
            const cacheable = attn_bcast != null and self.ablate == .none;
            if (cacheable and !attn_refresh and attn_bcast.?.blocks[bi].ctx != null) {
                at = attn_bcast.?.blocks[bi];
                at_owned = false;
            } else {
                const n1 = try rmsNormLast(h, b.norm1, cfg.norm_eps, s);
                defer _ = mlx.mlx_array_free(n1);
                const m1 = try modScaleShift(n1, mods[0], mods[1], plan.runs, a, s);
                defer _ = mlx.mlx_array_free(m1);
                const smode = if (self.ablate == .none) sparseModeForLayer(bi, self.blocks.len, self.sparse_policy) else SparseMode.dense;
                const spec: ?SparseSpec = if (smode == .dense) null else .{
                    .mode = smode,
                    .t = layout.latent_t,
                    .f = (layout.latent_h / PATCH_H) * (layout.latent_w / PATCH_W),
                    .video_start = layout.videoSegment().start,
                };
                at = if (self.ablate == .attn) try contig(m1, s) else try attnForward(&b.attn, m1, cfg, rope, self.ablate, spec, s);
                if (cacheable) {
                    if (attn_bcast.?.blocks[bi].ctx != null) _ = mlx.mlx_array_free(attn_bcast.?.blocks[bi]);
                    attn_bcast.?.blocks[bi] = at;
                    at_owned = false;
                }
            }
            defer if (at_owned) {
                _ = mlx.mlx_array_free(at);
            };
            const h1 = try modGate(h, mods[2], at, plan.runs, a, s);
            _ = mlx.mlx_array_free(h);
            h = h1;

            const n2 = try rmsNormLast(h, b.norm2, cfg.norm_eps, s);
            defer _ = mlx.mlx_array_free(n2);
            const m2 = try modScaleShift(n2, mods[3], mods[4], plan.runs, a, s);
            defer _ = mlx.mlx_array_free(m2);
            const mo = if (self.ablate == .mlp) try contig(m2, s) else try mlpForward(&b.mlp, m2, s);
            defer _ = mlx.mlx_array_free(mo);
            const h2 = try modGate(h, mods[5], mo, plan.runs, a, s);
            _ = mlx.mlx_array_free(h);
            h = h2;
        }
        defer _ = mlx.mlx_array_free(h);

        // Final layer: 1 modality, so the mod row is just the timestep row.
        var fmods: [2]mlx.mlx_array = undefined;
        var fmods_owned = true;
        if (self.adaln_tables) |tt| {
            fmods = tt.final;
            fmods_owned = false;
        } else {
            try self.final_adaln.?.forward(t_emb, cfg, true, &fmods, s);
        }
        defer if (fmods_owned) for (&fmods) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };
        const vseg = layout.videoSegment();
        const aseg = layout.audioSegment();
        const v_row = plan.runs[layout.segments.len - 1].mod_row / 3;
        const a_row = plan.runs[layout.segments.len - 2].mod_row / 3;

        const vout = try self.finalHead(h, fmods[0], fmods[1], vseg, v_row, self.video_out_w, self.video_out_b, s);
        errdefer _ = mlx.mlx_array_free(vout);
        const aout_raw = try self.finalHead(h, fmods[0], fmods[1], aseg, a_row, self.audio_out_w, self.audio_out_b, s);
        defer _ = mlx.mlx_array_free(aout_raw);

        // The sampler integrates a flat ODE on the VIDEO schedule. Scaling the
        // audio velocity by d(sigma_a)/d(sigma_v) makes that equal the audio
        // stream's true ODE on its own schedule. Both are negated: the model
        // predicts velocity, the sampler wants the denoise direction.
        const slope = timeShiftSlope(sigma_v, shift_v, shift_a);
        const negv = try scalarLike(-1.0, vout, s);
        defer _ = mlx.mlx_array_free(negv);
        const video = try mulA(vout, negv, s);
        _ = mlx.mlx_array_free(vout);
        errdefer _ = mlx.mlx_array_free(video);
        const nega = try scalarLike(@floatCast(-slope), aout_raw, s);
        defer _ = mlx.mlx_array_free(nega);
        const audio = try mulA(aout_raw, nega, s);
        return .{ .video = video, .audio = audio };
    }

    fn finalHead(self: *const Model, h: mlx.mlx_array, shift: mlx.mlx_array, scale: mlx.mlx_array, seg: Segment, row: u32, w: mlx.mlx_array, b: mlx.mlx_array, s: S) !mlx.mlx_array {
        const part = try sliceRows(h, @intCast(seg.start), @intCast(seg.end), s);
        defer _ = mlx.mlx_array_free(part);
        const nn = try rmsNormLast(part, self.final_norm, self.cfg.final_norm_eps, s);
        defer _ = mlx.mlx_array_free(nn);
        const sc = try sliceRows(scale, @intCast(row), @intCast(row + 1), s);
        defer _ = mlx.mlx_array_free(sc);
        const sh = try sliceRows(shift, @intCast(row), @intCast(row + 1), s);
        defer _ = mlx.mlx_array_free(sh);
        const one = try scalarLike(1.0, nn, s);
        defer _ = mlx.mlx_array_free(one);
        const sc1 = try addA(sc, one, s);
        defer _ = mlx.mlx_array_free(sc1);
        const m = try mulA(nn, sc1, s);
        defer _ = mlx.mlx_array_free(m);
        const mo = try addA(m, sh, s);
        defer _ = mlx.mlx_array_free(mo);
        // The output heads are fp32 islands; the reference casts here too.
        const f = try astype(mo, mlx.mlx_dtype.float32, s);
        defer _ = mlx.mlx_array_free(f);
        return denseLinear(f, w, b, s);
    }
};

// ── Text encoder (Qwen3-VL-32B, truncated to 50 layers) ─────────────────────
//
// H3's conditioning is the UNNORMALIZED hidden state after LM layer 50. The
// Comfy repack is truncated exactly there and ships no `model.norm`, so "tap
// layer 50" is simply "run every layer present and take the output".
//
// The presentation is NOT chat-templated: for t2va the ids are the raw prompt
// with NO special tokens and no prefix/suffix. Every position carries adaLN
// token tag 1 (text); only vision blocks would carry tag 0, and t2va has none.
//
// For text-only input Qwen3-VL's M-RoPE (mrope_section [24,20,20]) collapses to
// plain 1-D rotate-half RoPE, because all three axes share the running position.

pub const TeConfig = struct {
    hidden: c_int = 5120,
    heads: c_int = 64,
    kv_heads: c_int = 8,
    head_dim: c_int = 128,
    intermediate: c_int = 25600,
    layers: u32 = 50,
    theta: f64 = 5_000_000.0,
    eps: f32 = 1e-6,
};

const TeLayerW = struct {
    input_ln: mlx.mlx_array,
    post_ln: mlx.mlx_array,
    qw: MfLinear,
    kw: MfLinear,
    vw: MfLinear,
    ow: MfLinear,
    q_norm: mlx.mlx_array,
    k_norm: mlx.mlx_array,
    gate_w: MfLinear,
    up_w: MfLinear,
    down_w: MfLinear,

    fn deinit(self: *TeLayerW) void {
        inline for (.{ &self.qw, &self.kw, &self.vw, &self.ow, &self.gate_w, &self.up_w, &self.down_w }) |f| f.deinit();
        inline for (.{ self.input_ln, self.post_ln, self.q_norm, self.k_norm }) |f| _ = mlx.mlx_array_free(f);
    }
};

pub const TextEncoder = struct {
    allocator: std.mem.Allocator,
    cfg: TeConfig,
    dtype: mlx.mlx_dtype,
    embed_table: mlx.mlx_array,
    layers: []TeLayerW,

    pub fn load(allocator: std.mem.Allocator, w: *const Weights, cfg: TeConfig, dt: mlx.mlx_dtype, s: S) !TextEncoder {
        var self: TextEncoder = undefined;
        self.allocator = allocator;
        self.cfg = cfg;
        self.dtype = dt;
        const raw = try ownWeight(w, "model.embed_tokens.weight");
        defer _ = mlx.mlx_array_free(raw);
        self.embed_table = try astype(raw, dt, s);
        errdefer _ = mlx.mlx_array_free(self.embed_table);

        self.layers = try allocator.alloc(TeLayerW, cfg.layers);
        errdefer allocator.free(self.layers);
        const a = allocator;
        for (self.layers, 0..) |*layer, i| {
            const p = try std.fmt.allocPrint(a, "model.layers.{d}", .{i});
            defer a.free(p);
            const names = .{ "self_attn.q_proj", "self_attn.k_proj", "self_attn.v_proj", "self_attn.o_proj", "mlp.gate_proj", "mlp.up_proj", "mlp.down_proj" };
            var lin: [7]MfLinear = undefined;
            const in_dims = [7]c_int{ cfg.hidden, cfg.hidden, cfg.hidden, cfg.heads * cfg.head_dim, cfg.hidden, cfg.hidden, cfg.intermediate };
            inline for (names, 0..) |nm, j| {
                const full = try std.fmt.allocPrint(a, "{s}.{s}", .{ p, nm });
                defer a.free(full);
                lin[j] = try MfLinear.load(w, a, full, @intCast(in_dims[j]), dt, s);
            }
            // Norm weights stay f32: mlx_fast_rms_norm upcasts activations, and
            // a bf16 norm weight reintroduces the late-layer outlier divergence
            // mage_flow.zig documents.
            layer.* = .{
                .input_ln = try ownWeightAs(w, a, p, ".input_layernorm.weight", mlx.mlx_dtype.float32, s),
                .post_ln = try ownWeightAs(w, a, p, ".post_attention_layernorm.weight", mlx.mlx_dtype.float32, s),
                .qw = lin[0],
                .kw = lin[1],
                .vw = lin[2],
                .ow = lin[3],
                .q_norm = try ownWeightAs(w, a, p, ".self_attn.q_norm.weight", mlx.mlx_dtype.float32, s),
                .k_norm = try ownWeightAs(w, a, p, ".self_attn.k_norm.weight", mlx.mlx_dtype.float32, s),
                .gate_w = lin[4],
                .up_w = lin[5],
                .down_w = lin[6],
            };
        }
        return self;
    }

    pub fn deinit(self: *TextEncoder) void {
        _ = mlx.mlx_array_free(self.embed_table);
        for (self.layers) |*l| l.deinit();
        self.allocator.free(self.layers);
    }

    /// Raw prompt ids (NO special tokens) -> [L, hidden] layer-50 hidden state.
    /// Deliberately NOT final-normed: the checkpoint ships no `model.norm` and
    /// the reference sets `layer_norm_hidden_state=False`.
    pub fn encode(self: *const TextEncoder, ids: []const i32, s: S) !mlx.mlx_array {
        const seq: c_int = @intCast(ids.len);
        const cfg = self.cfg;

        const id_shape = [_]c_int{seq};
        const id_arr = mlx.mlx_array_new_data(ids.ptr, &id_shape, 1, mlx.mlx_dtype.int32);
        defer _ = mlx.mlx_array_free(id_arr);
        var emb = mlx.mlx_array_new();
        try mlx.check(mlx.mlx_take_axis(&emb, self.embed_table, id_arr, 0, s));
        var x = try reshape(emb, &[_]c_int{ 1, seq, cfg.hidden }, s);
        _ = mlx.mlx_array_free(emb);
        errdefer _ = mlx.mlx_array_free(x);

        var rope = try self.buildRope(seq, s);
        defer rope.deinit();
        const mask = try causalMask(seq, self.dtype, s);
        defer _ = mlx.mlx_array_free(mask);

        for (self.layers) |*layer| {
            const nx = try self.layerForward(layer, x, mask, rope, seq, s);
            _ = mlx.mlx_array_free(x);
            x = nx;
        }
        const out = try reshape(x, &[_]c_int{ seq, cfg.hidden }, s);
        _ = mlx.mlx_array_free(x);
        return out;
    }

    fn buildRope(self: *const TextEncoder, seq: c_int, s: S) !RopeTables {
        const hd: usize = @intCast(self.cfg.head_dim);
        const half = hd / 2;
        const n: usize = @intCast(seq);
        const buf = try self.allocator.alloc(f32, n * half * 2);
        defer self.allocator.free(buf);
        for (0..n) |i| {
            for (0..half) |j| {
                const inv = 1.0 / std.math.pow(f64, self.cfg.theta, @as(f64, @floatFromInt(2 * j)) / @as(f64, @floatFromInt(hd)));
                const ang = @as(f64, @floatFromInt(i)) * inv;
                buf[i * half * 2 + j] = @floatCast(@cos(ang));
                buf[i * half * 2 + half + j] = @floatCast(@sin(ang));
            }
        }
        const shape = [_]c_int{ n_c(n), @intCast(half * 2) };
        const arr = mlx.mlx_array_new_data(buf.ptr, &shape, 2, mlx.mlx_dtype.float32);
        defer _ = mlx.mlx_array_free(arr);
        var parts: [2]mlx.mlx_array = undefined;
        try splitEqual(arr, 2, 1, &parts, s);
        defer for (&parts) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };
        // [1, 1, seq, half] to broadcast against [1, H, seq, head_dim]
        const bshape = [_]c_int{ 1, 1, seq, @intCast(half) };
        const c0 = try reshape(parts[0], &bshape, s);
        defer _ = mlx.mlx_array_free(c0);
        const s0 = try reshape(parts[1], &bshape, s);
        defer _ = mlx.mlx_array_free(s0);
        var r: RopeTables = .{
            .cos = try astype(c0, self.dtype, s),
            .sin = try astype(s0, self.dtype, s),
        };
        errdefer r.deinit();
        return r;
    }

    fn layerForward(self: *const TextEncoder, layer: *const TeLayerW, x: mlx.mlx_array, mask: mlx.mlx_array, rope: RopeTables, seq: c_int, s: S) !mlx.mlx_array {
        const cfg = self.cfg;
        const xn = try rmsNormLast(x, layer.input_ln, cfg.eps, s);
        defer _ = mlx.mlx_array_free(xn);

        var qkv: [3]mlx.mlx_array = undefined;
        const heads = [3]c_int{ cfg.heads, cfg.kv_heads, cfg.kv_heads };
        inline for (.{ &layer.qw, &layer.kw, &layer.vw }, 0..) |lw, i| {
            const p = try lw.forward(xn, null, s);
            defer _ = mlx.mlx_array_free(p);
            const r4 = try reshape(p, &[_]c_int{ 1, seq, heads[i], cfg.head_dim }, s);
            if (i == 2) {
                defer _ = mlx.mlx_array_free(r4);
                const t = try transpose(r4, &[_]c_int{ 0, 2, 1, 3 }, s);
                defer _ = mlx.mlx_array_free(t);
                qkv[i] = try contig(t, s);
            } else {
                defer _ = mlx.mlx_array_free(r4);
                const nw = if (i == 0) layer.q_norm else layer.k_norm;
                const nn = try rmsNormLast(r4, nw, cfg.eps, s);
                defer _ = mlx.mlx_array_free(nn);
                const t = try transpose(nn, &[_]c_int{ 0, 2, 1, 3 }, s);
                defer _ = mlx.mlx_array_free(t);
                const tc = try contig(t, s);
                defer _ = mlx.mlx_array_free(tc);
                qkv[i] = try ropeHalf(tc, rope, cfg.head_dim, s);
            }
        }
        defer for (&qkv) |*p| {
            _ = mlx.mlx_array_free(p.*);
        };

        const scale: f32 = 1.0 / @sqrt(@as(f32, @floatFromInt(cfg.head_dim)));
        var attn = mlx.mlx_array_new();
        defer _ = mlx.mlx_array_free(attn);
        const null_sink = mlx.mlx_array{ .ctx = null };
        try mlx.check(mlx.mlx_fast_scaled_dot_product_attention(&attn, qkv[0], qkv[1], qkv[2], scale, "array", mask, null_sink, s));
        const at = try transpose(attn, &[_]c_int{ 0, 2, 1, 3 }, s);
        defer _ = mlx.mlx_array_free(at);
        const af = try reshape(at, &[_]c_int{ 1, seq, cfg.heads * cfg.head_dim }, s);
        defer _ = mlx.mlx_array_free(af);
        const o = try layer.ow.forward(af, null, s);
        defer _ = mlx.mlx_array_free(o);
        const h1 = try addA(x, o, s);
        defer _ = mlx.mlx_array_free(h1);

        const hn = try rmsNormLast(h1, layer.post_ln, cfg.eps, s);
        defer _ = mlx.mlx_array_free(hn);
        const g = try layer.gate_w.forward(hn, null, s);
        defer _ = mlx.mlx_array_free(g);
        const sg = try siluA(g, s);
        defer _ = mlx.mlx_array_free(sg);
        const u = try layer.up_w.forward(hn, null, s);
        defer _ = mlx.mlx_array_free(u);
        const gu = try mulA(sg, u, s);
        defer _ = mlx.mlx_array_free(gu);
        const d = try layer.down_w.forward(gu, null, s);
        defer _ = mlx.mlx_array_free(d);
        return addA(h1, d, s);
    }
};

inline fn n_c(v: usize) c_int {
    return @intCast(v);
}

/// Standard rotate-half RoPE on [1, H, seq, head_dim].
fn ropeHalf(x: mlx.mlx_array, rope: RopeTables, head_dim: c_int, s: S) !mlx.mlx_array {
    const half = @divExact(head_dim, 2);
    const x1 = try sliceLast4(x, 0, half, s);
    defer _ = mlx.mlx_array_free(x1);
    const x2 = try sliceLast4(x, half, head_dim, s);
    defer _ = mlx.mlx_array_free(x2);
    const a1 = try mulA(x1, rope.cos, s);
    defer _ = mlx.mlx_array_free(a1);
    const a2 = try mulA(x2, rope.sin, s);
    defer _ = mlx.mlx_array_free(a2);
    var o1 = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(o1);
    try mlx.check(mlx.mlx_subtract(&o1, a1, a2, s));
    const b1 = try mulA(x2, rope.cos, s);
    defer _ = mlx.mlx_array_free(b1);
    const b2 = try mulA(x1, rope.sin, s);
    defer _ = mlx.mlx_array_free(b2);
    const o2 = try addA(b1, b2, s);
    defer _ = mlx.mlx_array_free(o2);
    return concat(&[_]mlx.mlx_array{ o1, o2 }, 3, s);
}

/// Additive causal mask [1, 1, seq, seq]. Built with `where`, never by
/// multiplying an indicator by -inf: 0 * -inf is NaN, and a NaN mask passes a
/// parity loop that compares before it checks finiteness.
fn causalMask(seq: c_int, dt: mlx.mlx_dtype, s: S) !mlx.mlx_array {
    var rows = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(rows);
    try mlx.check(mlx.mlx_arange(&rows, 0, @floatFromInt(seq), 1, mlx.mlx_dtype.int32, s));
    const r = try reshape(rows, &[_]c_int{ seq, 1 }, s);
    defer _ = mlx.mlx_array_free(r);
    const c = try reshape(rows, &[_]c_int{ 1, seq }, s);
    defer _ = mlx.mlx_array_free(c);
    var keep = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(keep);
    try mlx.check(mlx.mlx_greater_equal(&keep, r, c, s));

    const zero = mlx.mlx_array_new_float(0);
    defer _ = mlx.mlx_array_free(zero);
    const neg = mlx.mlx_array_new_float(-std.math.inf(f32));
    defer _ = mlx.mlx_array_free(neg);
    var m = mlx.mlx_array_new();
    defer _ = mlx.mlx_array_free(m);
    try mlx.check(mlx.mlx_where(&m, keep, zero, neg, s));
    const m4 = try reshape(m, &[_]c_int{ 1, 1, seq, seq }, s);
    defer _ = mlx.mlx_array_free(m4);
    return astype(m4, dt, s);
}

