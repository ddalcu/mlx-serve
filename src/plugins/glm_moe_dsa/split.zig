/// The slot rows' bytes as the stream allocates them: each layer's prompt arrays and its grown ones.
fn slotBytesOf(g: glm.Geometry, prompt: u32, rows: []const u32) u64 {
    var floor: [n_bank]u32 = undefined;
    _ = bill.rowsAt(g, prompt, &floor);
    var n: u64 = 0;
    for (g.layers, rows, floor) |l, x, f| n += bill.slotArrays(l, f) + bill.slotArrays(l, x - f);
    return n;
}

