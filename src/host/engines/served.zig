//! The engines beside MLX (ds4, llama.cpp, the Neural Engine), each behind its `abi/engine.zig` table: which one
//! serves a model, and one opened model on its registry entry. Requests reach it through `requests.zig`.

const std = @import("std");
const build_options = @import("build_options");
const abi = @import("../../abi/engine.zig");
const engine_pick = @import("../../sdk/quant/gguf/engine_pick.zig");
const discovery = @import("../registry/discovery.zig");
const load_progress = @import("../registry/load_progress.zig");
const io_util = @import("../../sdk/util/io_util.zig");
const log = @import("../../sdk/util/log.zig");
const metrics_mod = @import("../metrics/metrics.zig");

/// The Model Settings `engine` spelling; `.mlx` has no table here.
pub const Kind = @import("../registry/model_settings.zig").Engine;

/// The table serving `kind`; null for MLX and for an engine this build leaves out.
pub fn table(kind: Kind) ?*const abi.Engine {
    return switch (kind) {
        .mlx => null,
        .ds4 => if (build_options.ds4_engine) &@import("../../engines/ds4/engine.zig").table else null,
        .llama => if (build_options.llama_engine) &@import("../../engines/llama/engine.zig").table else null,
        .ane => &@import("../../engines/ane/engine.zig").table,
    };
}

/// How a refusal names the engine.
pub fn displayName(kind: Kind) []const u8 {
    return switch (kind) {
        .mlx => "MLX",
        .ds4 => "the embedded ds4 engine (GGUF)",
        .llama => "the embedded llama.cpp engine (GGUF)",
        .ane => "the Neural Engine",
    };
}

/// The engine a `.gguf` at `path` (the file, or a dir holding one) goes to: `forced` (the model's engine setting, else
/// `--engine`), else its header (`engine_pick.preferredEngine`); a file or header that cannot be read goes to llama.cpp.
pub fn ggufEngine(io: std.Io, gpa: std.mem.Allocator, path: []const u8, forced: ?engine_pick.Engine) engine_pick.Engine {
    if (forced) |e| {
        log.info("[gguf] engine: {s} (forced by the model's engine setting or --engine)\n", .{@tagName(e)});
        return e;
    }
    const file = discovery.resolveGgufFile(io, gpa, path) catch |err| {
        log.warn("[gguf] route: cannot resolve gguf file ({s}); defaulting to llama\n", .{@errorName(err)});
        return .llama;
    };
    defer gpa.free(file);
    var info = engine_pick.readFromFile(io, gpa, file) catch |err| {
        log.warn("[gguf] route: metadata read failed ({s}); defaulting to llama\n", .{@errorName(err)});
        return .llama;
    };
    defer info.deinit(gpa);
    const e = engine_pick.preferredEngine(info);
    log.info("[gguf] engine: {s} (arch={s}, ds4-lora={}, ds4-unloadable={}, shards={d})\n", .{
        @tagName(e),
        info.architecture orelse "?",
        info.has_ds4_lora_rank,
        info.ds4_unloadable,
        info.split_count,
    });
    return e;
}

pub fn fromGguf(e: engine_pick.Engine) Kind {
    return switch (e) {
        .ds4 => .ds4,
        .llama => .llama,
    };
}

/// Whether an MLX pack asks for the Neural Engine: its `ane` setting, else `--ane`.
pub fn aneWanted(config: anytype, flag: bool) bool {
    return config.ane_override orelse flag;
}

/// What the host's metrics sum across the engines beside MLX: requests not yet prefilled, their prompt tokens
/// (`abi.Progress.prefill_*`), tokens generated by the ones decoding.
pub const Gauges = struct {
    prefilling: std.atomic.Value(u64) = .init(0),
    prefill_todo: std.atomic.Value(u64) = .init(0),
    prefill_done: std.atomic.Value(u64) = .init(0),
    generated: std.atomic.Value(u64) = .init(0),
};

/// One opened model. Lives on the heap from `open` to `close`: the engine holds `&host`.
pub const Served = struct {
    gpa: std.mem.Allocator,
    kind: Kind,
    table: *const abi.Engine,
    handle: *anyopaque,
    info: abi.Info,
    host: abi.Host,
    progress: *load_progress.Progress,
    gauges: *Gauges,
    metrics: ?*metrics_mod.Metrics,

    pub const Spec = struct {
        model_dir: []const u8,
        model_type: []const u8 = "",
        context: u32 = 0,
        max_concurrent: u32 = 1,
        settings_json: []const u8 = "",
    };

    /// Opens `kind` on `spec`; a refusal is the engine's own error by name (`OpenError`), logged.
    pub fn open(gpa: std.mem.Allocator, kind: Kind, spec: Spec, progress: *load_progress.Progress, gauges: *Gauges, metrics: ?*metrics_mod.Metrics) !*Served {
        const t = table(kind) orelse return error.EngineUnavailable;
        const s = try gpa.create(Served);
        errdefer gpa.destroy(s);
        s.* = .{
            .gpa = gpa,
            .kind = kind,
            .table = t,
            .handle = undefined,
            .info = undefined,
            .host = .{ .ctx = s, .log = hostLog, .wake = hostWake, .progress = hostProgress },
            .progress = progress,
            .gauges = gauges,
            .metrics = metrics,
        };
        const o: abi.Open = .{
            .model_dir = abi.span(u8, spec.model_dir),
            .model_type = abi.span(u8, spec.model_type),
            .config_json = .{},
            .context = spec.context,
            .max_concurrent = spec.max_concurrent,
            .memory_budget = 0,
            .settings_json = abi.span(u8, spec.settings_json),
            .options_json = .{},
            .host = &s.host,
        };
        var v: abi.Verdict = .{};
        s.handle = t.open(&o, &s.info, &v) orelse {
            log.err("[{s}] engine open failed: {s}\n", .{ @tagName(kind), abi.items(u8, v.why) });
            return openError(abi.items(u8, v.why));
        };
        log.info("[{s}] {s}\n", .{ @tagName(kind), abi.items(u8, s.info.startup) });
        return s;
    }

    /// Cancels and finishes every request, then frees the engine.
    pub fn close(s: *Served) void {
        s.table.close(s.handle);
        s.gpa.destroy(s);
    }

    pub fn caps(s: *const Served) abi.Caps {
        return s.info.caps;
    }

    /// What the engine holds now (its weights, KV and caches; outside MLX's counters).
    pub fn residentBytes(s: *const Served) u64 {
        var m: abi.Memory = .{};
        s.table.memory(s.handle, &m);
        return m.active;
    }

    /// `text` through the engine's own vocabulary; `specials` adds the model's BOS where the engine has one.
    pub fn tokenize(s: *const Served, gpa: std.mem.Allocator, text: []const u8, specials: bool) ![]u32 {
        const f = s.table.tokenize orelse return error.NoTokenizer;
        return fill(gpa, text.len + 8, f, .{ s.handle, abi.span(u8, text), specials });
    }

    /// The engine's own chat template over `chat_json` (`Caps.owns_template`).
    pub fn render(s: *const Served, gpa: std.mem.Allocator, chat_json: []const u8) ![]u32 {
        const f = s.table.render orelse return error.NoChatTemplate;
        return fill(gpa, chat_json.len + 64, f, .{ s.handle, abi.span(u8, chat_json) });
    }

    /// Each id's bytes, concatenated.
    pub fn decode(s: *const Served, gpa: std.mem.Allocator, ids: []const u32) ![]u8 {
        const f = s.table.token_bytes orelse return error.NoTokenizer;
        var out: std.ArrayList(u8) = .empty;
        errdefer out.deinit(gpa);
        for (ids) |id| try out.appendSlice(gpa, abi.items(u8, f(s.handle, id)));
        return out.toOwnedSlice(gpa);
    }

    /// The model's own chat template (a GGUF's embedded one); null when the engine ships none.
    pub fn chatTemplate(s: *const Served) ?[]const u8 {
        const f = s.table.chat_template orelse return null;
        const t = abi.items(u8, f(s.handle));
        return if (t.len == 0) null else t;
    }

    /// The ids a prompt may carry: the engine's vocabulary when it owns one.
    pub fn vocabSize(s: *const Served) u32 {
        return s.info.vocab_size;
    }
};

/// The errors the engines' opens name: a load failure keeps its name on the entry and in the 503.
pub const OpenError = error{ EngineOpenFailed, SplitGgufUnsupported, SessionCreateFailed, KernelExtractionFailed, OutOfMemory, AneUnavailable, UnsupportedArch, LoadFailed, InvalidSettings };

fn openError(why: []const u8) OpenError {
    inline for (@typeInfo(OpenError).error_set.error_names.?) |name| if (std.mem.eql(u8, why, name)) return @field(OpenError, name);
    return error.EngineOpenFailed;
}

/// Calls a fill-style entry point (`out`, `cap` last, the full count returned) until its output fits.
fn fill(gpa: std.mem.Allocator, guess: usize, f: anytype, args: anytype) ![]u32 {
    var cap = guess;
    while (true) {
        const buf = try gpa.alloc(u32, cap);
        const n = @call(.auto, f, args ++ .{ buf.ptr, cap });
        if (n <= cap) return if (gpa.resize(buf, n)) buf[0..n] else blk: {
            defer gpa.free(buf);
            break :blk try gpa.dupe(u32, buf[0..n]);
        };
        gpa.free(buf);
        cap = n;
    }
}

fn hostLog(_: *anyopaque, level: u8, msg: abi.Str) callconv(.c) void {
    const m = abi.items(u8, msg);
    if (level == 0) log.err("{s}\n", .{m}) else log.info("{s}\n", .{m});
}

fn hostWake(_: *anyopaque) callconv(.c) void {}

fn hostProgress(ctx: *anyopaque, what: abi.Progress, n: i64) callconv(.c) void {
    const s: *Served = @ptrCast(@alignCast(ctx));
    const delta: u64 = @bitCast(n);
    switch (what) {
        .load_total => s.progress.begin(.ane_programs, @intCast(@max(n, 0)), io_util.nowMsMonotonic(std.Io.Threaded.global_single_threaded.io())),
        .load_done => s.progress.add(delta),
        .load_slow => s.progress.compiling.store(true, .monotonic),
        .prefill_todo => _ = s.gauges.prefill_todo.fetchAdd(delta, .monotonic),
        .prefill_done => _ = s.gauges.prefill_done.fetchAdd(delta, .monotonic),
    }
}

